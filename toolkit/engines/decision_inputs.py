#!/usr/bin/env python3
"""Decision inputs of an engine card (F6 evidence dossier, owner decision 2026-11-12).

    python3 toolkit/engines/decision_inputs.py --self-test

Per package component, the unit attributes, engine parameters (their values or priors) and card tables the
component's effect depends on. The owner's sign-off requires a checked, sourced evidence-dossier entry for every one
that a spec's options use (toolkit/spec/evidence_dossier.py). An engine declares them in its card directory: a
`decision_inputs` key in card.yaml and/or a decision_inputs.yaml beside it (merged; a component declared twice is
refused); an engine class without a card directory may set a `DECISION_INPUTS` class attribute. YAML, not code, so
that the declaration never changes an engine's code fingerprint (toolkit/engines/contract.py code_fingerprint hashes
the engine directory's .py files and the contract), and a card regenerated by `engine.py --card` keeps it.

    decision_inputs:
      <component> | "*":              "*": every component (configured engines name their components from the spec)
        inactive: [values]            values with no effect: nothing to check
        inputs: [{kind, name, why[, if_on_card]}]
                                      kind: unit_attribute | parameter | card_table; "{component}" in a name is
                                      replaced by the component's name; if_on_card: true keeps the input only when the
                                      configured engine's card has it, and a glob ("s0:*") expands to each match
    not_decision_inputs: {"<kind>:<name>": reason}   card entries that drive no component's effect (the
                                      completeness check: every card parameter and unit attribute is an input or here)
        by_value: {value: [inputs]}   added for that value
        none_reason: "..."            required when the component has no inputs at all (never blank)

Nothing here names a disease; the names come from each engine's card.
"""
from __future__ import annotations

import math
import os
import sys

KINDS = ("unit_attribute", "parameter", "card_table")
FILE = "decision_inputs.yaml"
FIELDS = ("inactive", "inputs", "by_value", "none_reason")
INPUT_FIELDS = ("kind", "name", "why", "if_on_card")


def _inputs_problems(where: str, ins, vocab: dict) -> list[str]:
    if ins is None:
        return []
    if not isinstance(ins, list):
        return [f"{where}: a list of {{kind, name, why}}"]
    bad = []
    for i in ins:
        if not isinstance(i, dict) or not all(isinstance(i.get(k), str) and i[k].strip() for k in ("kind", "name", "why")):
            bad.append(f"{where}: each input needs kind, name and why ({i!r})")
            continue
        bad += [f"{where}: {i['name']}: unknown input field {k!r}" for k in i if k not in INPUT_FIELDS]
        if "if_on_card" in i and not isinstance(i["if_on_card"], bool):
            bad.append(f"{where}: {i['name']}: if_on_card is true or false")
        if i["kind"] not in KINDS:
            bad.append(f"{where}: {i['name']}: kind {i['kind']!r} not in {KINDS}")
        elif "*" in i["name"] and i.get("if_on_card") is not True:
            bad.append(f"{where}: {i['name']}: a glob name resolves against the configured card: mark it if_on_card")
        elif vocab.get(i["kind"]) is not None and not _conditional(i) and i["name"] not in vocab[i["kind"]]:
            bad.append(f"{where}: {i['kind']} {i['name']!r} is not on the engine's card")
    return bad


def _conditional(i: dict) -> bool:
    """An input whose name depends on the component or the configuration (checked once the card is configured)."""
    return "{" in i["name"] or "*" in i["name"] or i.get("if_on_card") is True


def resolve(inputs: list, vocab: dict | None) -> list:
    """The inputs as the configured card names them: an if_on_card input is kept when the card has it (a glob expands
    to every match), others must be on the card. `vocab`: {kind: names} of the configured engine (None: not needed
    unless an input is if_on_card or a glob). Raises ValueError when an unconditional input is not on the card."""
    import fnmatch
    out = []
    for i in inputs:
        cond = i.get("if_on_card") is True or "*" in i["name"]
        known = (vocab or {}).get(i["kind"])
        if not cond:
            if known is not None and i["name"] not in known:
                raise ValueError(f"{i['kind']} {i['name']!r} is not on the configured engine's card")
            out.append(i)
            continue
        if vocab is None:
            raise ValueError(f"{i['kind']} {i['name']!r}: the configured card is needed to resolve it")
        out += [dict(i, name=n) for n in sorted(known or []) if fnmatch.fnmatchcase(n, i["name"])]
    return out


def outcome_inputs(oi, outcomes) -> list:
    """The outcome-level inputs (`outcome_inputs: {<outcome> | "*": [inputs]}`) the decision's outcomes need: what
    every arm uses to compute them (treatment, fatality, DALY weights), required whatever the components. "*" applies
    to every outcome; "{outcome}" in a name is the outcome's name."""
    out, seen = [], set()
    for o in outcomes:
        for i in list((oi or {}).get("*") or []) + list((oi or {}).get(o) or []):
            if isinstance(i, dict) and isinstance(i.get("name"), str):
                j = dict(i, name=i["name"].replace("{outcome}", str(o)))
                if (j["kind"], j["name"]) not in seen:
                    seen.add((j["kind"], j["name"]))
                    out.append(j)
    return out


def outcome_problems(oi) -> list[str]:
    """Problems of an `outcome_inputs` declaration (None: none declared)."""
    if oi is None:
        return []
    if not isinstance(oi, dict):
        return ["outcome_inputs: a mapping {outcome | \"*\": [inputs]}"]
    bad = []
    for o, ins in oi.items():
        bad += _inputs_problems(f"outcome_inputs.{o}", ins, {})
        if not ins:
            bad.append(f"outcome_inputs.{o}: give its inputs, or leave the outcome out")
    return bad


def load_outcome_inputs(engine_dir: str):
    """decision_inputs.yaml's `outcome_inputs`, or None."""
    import yaml
    p = os.path.join(engine_dir, FILE)
    if not os.path.isfile(p):
        return None
    with open(p, encoding="utf-8") as f:
        doc = yaml.safe_load(f) or {}
    return doc.get("outcome_inputs") if isinstance(doc, dict) else None


def coverage_problems(decl: dict, excluded: dict, vocab: dict, oi=None) -> list[str]:
    """The card's parameters and unit attributes ("<kind>:<name>") that no component or outcome declares as an input
    (a glob, {component} or {outcome} pattern covers what it matches) and that are not excluded with a reason: what
    the declaration may have omitted. `excluded`: {"<kind>:<name>": reason}."""
    import fnmatch
    pats = [(i["kind"], i["name"].replace("{component}", "*")) for d in (decl or {}).values() if isinstance(d, dict)
            for i in list(d.get("inputs") or []) + [x for xs in (d.get("by_value") or {}).values() for x in xs or []]
            if isinstance(i, dict) and isinstance(i.get("name"), str)]
    pats += [(i["kind"], i["name"].replace("{outcome}", "*")) for ins in (oi or {}).values() for i in ins or []
             if isinstance(i, dict) and isinstance(i.get("name"), str)]
    ex = {k for k, why in (excluded or {}).items() if isinstance(why, str) and why.strip()}
    return [f"{k}:{n}" for k in ("parameter", "unit_attribute") for n in vocab.get(k) or []
            if f"{k}:{n}" not in ex and not any(pk == k and fnmatch.fnmatchcase(n, pn) for pk, pn in pats)]


def load_excluded(engine_dir: str) -> dict:
    """decision_inputs.yaml's `not_decision_inputs`: {"<kind>:<name>": reason} for card entries that drive no
    component's effect (the completeness check's exclusions)."""
    import yaml
    p = os.path.join(engine_dir, FILE)
    if not os.path.isfile(p):
        return {}
    with open(p, encoding="utf-8") as f:
        doc = yaml.safe_load(f) or {}
    ex = doc.get("not_decision_inputs") if isinstance(doc, dict) else None
    return ex if isinstance(ex, dict) else {}


def problems(decl, components=None, unit_attributes=None, parameters=None, tables=None) -> list[str]:
    """Problems of a declaration (empty: valid). With the card's vocabulary given, every name must be on the card and,
    unless "*" is declared, every card component must be declared (fail closed)."""
    if not isinstance(decl, dict) or not decl:
        return ["decision_inputs: a mapping {component: {inputs, ...}}"]
    vocab = {"unit_attribute": unit_attributes, "parameter": parameters, "card_table": tables}
    bad = []
    for c, d in decl.items():
        where = f"decision_inputs.{c}"
        if components is not None and c != "*" and c not in components:
            bad.append(f"{where}: not a component of the engine")
        if not isinstance(d, dict):
            bad.append(f"{where}: a mapping {{{', '.join(FIELDS)}}}")
            continue
        bad += [f"{where}: unknown field {k!r}" for k in d if k not in FIELDS]
        bad += _inputs_problems(f"{where}.inputs", d.get("inputs"), vocab)
        bv = d.get("by_value") or {}
        if not isinstance(bv, dict):
            bad, bv = bad + [f"{where}.by_value: a mapping value -> inputs"], {}
        for v, ins in bv.items():
            bad += _inputs_problems(f"{where}.by_value.{v}", ins, vocab)
            if components is not None and c in components and str(v) not in map(str, components[c]):
                bad.append(f"{where}.by_value: {v!r} is not a value of the component")
        if not d.get("inputs") and not bv and not (isinstance(d.get("none_reason"), str) and d["none_reason"].strip()):
            bad.append(f"{where}: no inputs: say why (none_reason)")
    if components is not None and "*" not in decl:
        bad += [f"decision_inputs: card component {c!r} is not declared" for c in components if c not in decl]
    return bad


def merge(*decls) -> dict:
    """One declaration from several (card.yaml's key, decision_inputs.yaml); a component declared twice: ValueError."""
    out: dict = {}
    for d in decls:
        if d is not None and not isinstance(d, dict):
            raise ValueError("decision_inputs: a mapping {component: {...}}")
        for c, v in (d or {}).items():
            if c in out:
                raise ValueError(f"decision_inputs: component {c!r} is declared twice")
            out[c] = v
    return out


def load(engine_dir: str) -> dict | None:
    """card.yaml's `decision_inputs` merged with decision_inputs.yaml in `engine_dir`; None when neither declares any.
    A file that cannot be read or parsed raises (fail closed)."""
    import yaml
    found = []
    for f in ("card.yaml", FILE):
        p = os.path.join(engine_dir, f)
        if os.path.isfile(p):
            with open(p, encoding="utf-8") as fh:
                doc = yaml.safe_load(fh) or {}
            if not isinstance(doc, dict):
                raise ValueError(f"{p}: not a mapping")
            if doc.get("decision_inputs") is not None:
                found.append(doc["decision_inputs"])
    return merge(*found) if found else None


def component_inputs(decl, component: str, value) -> list | None:
    """The inputs component=value depends on ([] for an inactive value); None when the declaration cannot map it."""
    if not isinstance(decl, dict):
        return None
    d = decl.get(component, decl.get("*"))
    if not isinstance(d, dict):
        return None
    if str(value) in map(str, d.get("inactive") or []):
        return []
    bv = {str(k): v for k, v in (d.get("by_value") or {}).items()}
    return [dict(i, name=str(i.get("name", "")).replace("{component}", str(component)))
            for i in list(d.get("inputs") or []) + list(bv.get(str(value)) or []) if isinstance(i, dict)]


def dependency_problems(engine, unit, horizon, outcome: str, decl, oi=None, components=None, base_params=None,
                        step: float = 0.2, rel_tol: float = 1e-6, seed: int = 1) -> list[str]:
    """Per-component completeness, by perturbation, not by presence anywhere (#218 review round 3). For each active
    component value: its incremental effect on `outcome` (per capita, without it minus with it) is recomputed after
    moving each engine parameter and each numeric unit attribute by `step` (relative; absolute from 0; inside its
    range). An input that moves the effect must be declared for that component, or as an outcome input; one that is
    excluded (not_decision_inputs) or declared only for another component is a problem.
    `components`: {component: value} (default: each card component at its first active value)."""
    import fnmatch
    from toolkit.engines.contract import Package, UnitSpec
    card = engine.describe()
    comps = components or {c: next(v for v in vals if is_active(decl, c, v)) for c, vals in card.components.items()
                           if any(is_active(decl, c, v) for v in vals)}
    base = dict(base_params or {})

    def eff(params, attrs, c, v):
        u = UnitSpec(unit.id, attrs)
        a = engine.run(params, u, Package("none", {}), horizon, seed).per_capita[outcome]
        b = engine.run(params, u, Package(c, {c: v}), horizon, seed).per_capita[outcome]
        return sum(a.values()) - sum(b.values())

    def moved(x, lo=None, hi=None):
        y = x * (1 + step) if x else step
        if hi is not None and y > hi:
            y = x * (1 - step) if x else -step
        if lo is not None and y < lo:
            y = lo if lo != x else (hi if hi is not None else x)
        return y
    out = []
    for c, v in comps.items():
        allowed = [(i["kind"], i["name"].replace("{component}", c)) for i in component_inputs(decl, c, v) or []]
        allowed += [(i["kind"], i["name"]) for i in outcome_inputs(oi, [outcome])]
        e0 = eff(base, unit.attributes, c, v)

        def ok(kind, name):
            return any(k == kind and fnmatch.fnmatchcase(name, n) for k, n in allowed)
        for p in engine.parameters():
            x = float(base.get(p.name, p.value))
            y = moved(x, p.lo, p.hi)
            if y == x:
                continue
            e1 = eff(dict(base, **{p.name: y}), unit.attributes, c, v)
            if not math.isclose(e0, e1, rel_tol=rel_tol, abs_tol=1e-15) and not ok("parameter", p.name):
                out.append(f"{c}={v}: parameter {p.name} moves its effect ({e0:.6g} -> {e1:.6g}) but is not one of "
                           "its declared inputs")
        for a, x in unit.attributes.items():
            if isinstance(x, bool) or not (isinstance(x, (int, float)) or (
                    isinstance(x, list) and x and all(isinstance(z, (int, float)) and not isinstance(z, bool) for z in x))):
                continue
            lo, hi = ((card.valid_ranges or {}).get(a) or [None, None])[:2]
            y = [moved(float(z), lo, hi) for z in x] if isinstance(x, list) else moved(float(x), lo, hi)
            try:
                e1 = eff(base, dict(unit.attributes, **{a: y}), c, v)
            except ValueError:          # outside what the engine accepts: move the other way
                y = [float(z) * (1 - step) for z in x] if isinstance(x, list) else float(x) * (1 - step)
                e1 = eff(base, dict(unit.attributes, **{a: y}), c, v)
            if not math.isclose(e0, e1, rel_tol=rel_tol, abs_tol=1e-15) and not ok("unit_attribute", a):
                out.append(f"{c}={v}: unit attribute {a} moves its effect ({e0:.6g} -> {e1:.6g}) but is not one of "
                           "its declared inputs")
    return out


def is_active(decl, component: str, value) -> bool:
    """Whether component=value has an effect: declared, and not one of its inactive values."""
    d = decl.get(component, decl.get("*")) if isinstance(decl, dict) else None
    return isinstance(d, dict) and str(value) not in map(str, d.get("inactive") or [])


def card_vocabulary(engine_dir: str) -> dict:
    """The components, unit attributes, parameter names and top-level tables of the card.yaml in `engine_dir`, as
    keyword arguments of problems()."""
    import yaml
    with open(os.path.join(engine_dir, "card.yaml"), encoding="utf-8") as f:
        c = yaml.safe_load(f) or {}
    return {"components": c.get("components") or {}, "unit_attributes": c.get("unit_attributes") or {},
            "parameters": [p.get("name") for p in c.get("parameters") or [] if isinstance(p, dict)],
            "tables": [k for k, v in c.items() if isinstance(v, (dict, list))]}


def _self_test() -> int:
    import tempfile
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    if root not in sys.path:            # run as a script: the repo root, for the toy engine (DI11)
        sys.path.insert(0, root)
    fails = []

    def ok(cond, msg):
        print(("PASS " if cond else "FAIL ") + msg)
        if not cond:
            fails.append(msg)

    decl = {"a": {"inactive": [0], "inputs": [{"kind": "parameter", "name": "eff_a", "why": "its effect"},
                                              {"kind": "unit_attribute", "name": "x", "why": "transmission"}],
                  "by_value": {"1": [{"kind": "card_table", "name": "benchmarks", "why": "trial table"}]}},
            "b": {"inputs": [], "none_reason": "toy: closed form"}}
    kw = {"components": {"a": [0, 1], "b": [0, 1]}, "unit_attributes": {"x": ""}, "parameters": ["eff_a"],
          "tables": ["benchmarks"]}
    bad = problems({"a": {"inputs": [{"kind": "parameter", "name": "nope", "why": "w"},
                                     {"kind": "colour", "name": "x", "why": "w"}]},
                    "zz": {"inputs": [], "none_reason": "r"}}, **kw)
    ok(problems(decl, **kw) == [] and any("nope" in s for s in bad) and any("colour" in s for s in bad)
       and any("zz" in s for s in bad) and any("'b'" in s and "not declared" in s for s in bad),
       f"DI1 a declaration names card components, attributes and parameters; an unknown one, an unknown kind and an "
       f"undeclared card component are problems: {bad}")
    ok(any("none_reason" in s for s in problems({"a": {"inputs": []}, "b": decl["b"]}, **kw)),
       "DI2 a component with no inputs must say why (none_reason): it is never blank")
    ins = component_inputs(decl, "a", 1)
    ok([i["name"] for i in ins] == ["eff_a", "x", "benchmarks"] and component_inputs(decl, "a", 0) == []
       and component_inputs(decl, "b", 1) == [] and component_inputs(decl, "c", 1) is None
       and component_inputs(None, "a", 1) is None
       and [i["name"] for i in component_inputs({"*": {"inputs": [{"kind": "parameter", "name": "e:{component}",
                                                                   "why": "w"}]}}, "q", 1)] == ["e:q"],
       "DI3 component_inputs: the inputs and the value's extra inputs; none for an inactive value; None (cannot map, "
       "fail closed) for an undeclared component or engine; `*` covers configured component names")
    try:
        merge({"a": decl["a"]}, {"a": decl["a"]})
        ok(False, "DI4 two declarations of one component are refused")
    except ValueError:
        ok(merge({"a": decl["a"]}, {"b": decl["b"]}) == decl, "DI4 two declarations of one component are refused; "
                                                              "disjoint ones merge")
    import yaml
    with tempfile.TemporaryDirectory() as d:
        yaml.safe_dump({"name": "t", "decision_inputs": {"a": decl["a"]}}, open(os.path.join(d, "card.yaml"), "w"))
        yaml.safe_dump({"decision_inputs": {"b": decl["b"]}}, open(os.path.join(d, FILE), "w"))
        got = load(d)
        open(os.path.join(d, FILE), "w").write("decision_inputs: {a: [unclosed\n")
        try:
            load(d)
            broken = False
        except Exception:  # noqa: BLE001 -- a parse error of any type is the expected refusal
            broken = True
        ok(got == decl and broken and load(os.path.join(d, "nowhere")) is None,
           "DI5 the card's key and decision_inputs.yaml merge; an unparseable file raises; no file declares nothing")
    # DI6-DI9 (#218 review round 1): configured engines, malformed entries, completeness against the card
    try:
        conf = {"*": {"inputs": [
            {"kind": "parameter", "name": "efficacy:{component}", "why": "w"},
            {"kind": "parameter", "name": "r0", "why": "w", "if_on_card": True},
            {"kind": "parameter", "name": "q", "why": "w", "if_on_card": True},
            {"kind": "parameter", "name": "s0:*", "why": "w", "if_on_card": True},
            {"kind": "unit_attribute", "name": "reach:{component}", "why": "w", "if_on_card": True}]}}
        vocab = {"parameter": ["q", "efficacy:c", "s0:g1", "s0:g2"], "unit_attribute": ["N", "reach:c"]}
        got = sorted(f"{i['kind']}:{i['name']}" for i in resolve(component_inputs(conf, "c", 1), vocab))
        ok(got == ["parameter:efficacy:c", "parameter:q", "parameter:s0:g1", "parameter:s0:g2", "unit_attribute:reach:c"],
           f"DI6 inputs marked if_on_card (and globs) resolve against the configured card: q, not r0; s0 per group; "
           f"the campaign's reach: {got}")
        try:
            resolve([{"kind": "parameter", "name": "efficacy:c", "why": "w"}], {"parameter": ["q"]})
            ok(False, "DI7 an input that is not if_on_card and is not on the configured card is refused")
        except ValueError:
            ok(True, "DI7 an input that is not if_on_card and is not on the configured card is refused")
        bad = problems({"a": {"inputs": ["eff_a", {"kind": "parameter", "name": "s*", "why": "w"},
                                         {"kind": "parameter", "name": "x", "why": "w", "colour": 1}]}})
        ok(any("each input" in s for s in bad) and any("glob" in s for s in bad) and any("colour" in s for s in bad),
           f"DI8 a non-mapping input, a glob not marked if_on_card and an unknown input field are problems: {bad}")
        cov = coverage_problems({"a": {"inputs": [{"kind": "parameter", "name": "eff_a", "why": "w"}]}},
                                {"unit_attribute:x": "the toy's transmission index is calibrated"},
                                {"parameter": ["eff_a", "base"], "unit_attribute": ["x", "group"]})
        ok(cov == ["parameter:base", "unit_attribute:group"],
           f"DI9 every card parameter and unit attribute is a declared input or excluded with a reason: {cov}")
    except NameError as e:
        ok(False, f"DI6-DI9: {e}")
    # DI10 (#218 review round 2): inputs every arm uses to compute the decision's outcome, by outcome
    try:
        oi = {"*": [{"kind": "unit_attribute", "name": "ft", "why": "w"},
                    {"kind": "unit_attribute", "name": "ratio:{outcome}", "why": "w", "if_on_card": True}],
              "dalys": [{"kind": "parameter", "name": "dw", "why": "w"}]}
        got = [i["name"] for i in outcome_inputs(oi, ["dalys"])]
        ok(got == ["ft", "ratio:dalys", "dw"] and [i["name"] for i in outcome_inputs(oi, ["cases"])] == ["ft", "ratio:cases"]
           and outcome_problems(oi) == [] and outcome_problems({"dalys": ["dw"]})
           and coverage_problems({}, {}, {"parameter": ["dw"], "unit_attribute": ["ft"]}, oi) == [],
           f"DI10 outcome inputs: every outcome's plus the outcome's own, {{outcome}} substituted; malformed ones are "
           f"problems; they count for completeness: {got}")
    except NameError as e:
        ok(False, f"DI10: {e}")
    # DI11 (#218 review round 3): completeness per component, by perturbation, not by presence anywhere
    try:
        from toolkit.engines.contract import Horizon, ToyEngine, UnitSpec
        toy, h = ToyEngine(), Horizon(0, 3, (0, 3), {})
        part = {"a": {"inputs": [{"kind": "parameter", "name": "eff_a", "why": "w"}]},
                "b": {"inputs": [{"kind": "parameter", "name": "eff_b", "why": "w"}]}}
        got = dependency_problems(toy, UnitSpec("u", {"x": 0.5}), h, "cases", part, components={"a": 1, "b": 1})
        full = {c: {"inputs": [{"kind": "parameter", "name": f"eff_{c}", "why": "w"},
                               {"kind": "parameter", "name": "base", "why": "w"},
                               {"kind": "parameter", "name": "k", "why": "w"},
                               {"kind": "parameter", "name": "noise", "why": "w"},
                               {"kind": "unit_attribute", "name": "x", "why": "w"}]} for c in ("a", "b")}
        swapped = {"a": full["b"], "b": full["a"]}
        ok(any("a=1: parameter base" in g for g in got) and any("unit attribute x" in g for g in got)
           and dependency_problems(toy, UnitSpec("u", {"x": 0.5}), h, "cases", full, components={"a": 1, "b": 1}) == []
           and any("a=1: parameter eff_a" in g for g in dependency_problems(toy, UnitSpec("u", {"x": 0.5}), h,
                                                                            "cases", swapped, components={"a": 1, "b": 1})),
           f"DI11 an input that moves a component's effect must be declared for that component (declared for another "
           f"one, or not at all, is a problem): {got[:3]}")
    except NameError as e:
        ok(False, f"DI11: {e}")
    if fails:
        print(f"FAILED: {len(fails)} case(s)")
        return 1
    print("OK: all self-test cases passed.")
    return 0


if __name__ == "__main__":
    if sys.argv[1:2] == ["--self-test"]:
        sys.exit(_self_test())
    print(__doc__)

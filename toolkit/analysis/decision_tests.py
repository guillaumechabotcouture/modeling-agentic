"""Decision tests (spike lesson 8): does the plan change when a quantity is varied?

Types (spec `analysis.decision_tests`):
  interaction_rescale  the spike's DT1: the increment of `components` on top of any of `with_any`
                       is rescaled so the engine's interaction odds ratio in the benchmark setting
                       equals each value. The arm odds ratios come only from the engine's verified
                       benchmark results (toolkit/engines/benchmark.py verified_benchmarks: written by
                       the runner for this engine's current code), never from the spec (Codex P1-13).
                       A value the rescaling cannot reach (scale outside [0, MAX_SCALE]) is rejected,
                       and every reached value is checked: the achieved interaction equals the
                       requested one (Codex P1-12);
  parameter_value      an engine parameter set to each value (an emulator input on the emulator path);
  group_rule           a constraints.group_rules rule removed (or `add:` a rule) and the plan re-solved;
  envelope             the plan re-solved at each envelope;
  prior_range          (automatic, v2d note §2.4) one per prior-dominated parameter the draws vary
                       (toolkit/spec/priors.py): the parameter at each end of its declared range, the
                       calibration redone, the plan re-solved. Generated by the harness, id
                       `prior_range_<parameter>`; the spec cannot declare or remove one.
A test with at least one usable value writes `models/decision_tests/<id>.yaml` in the Phase 49
result schema (finding, varied, criterion, decision_changes, recommendation.with / without,
share_units_changed, share_threshold) with `produced_by: harness`. A test with none writes no
result file (a declaration citing it is then invalid) and is reported as not run, with why.

Relevance, up front: when a test changes only benefits, and every benefit it changes goes down and
belongs to a package no unit receives in the point plan, the point plan stays optimal (its value is
unchanged and no alternative improves). The file then says first that the test cannot move the plan.
Statements are words only; every number in results.md comes from computed claims (Codex P1-4).
"""
from __future__ import annotations

import copy
import math
import os

import numpy as np
import yaml

from toolkit.alloc import packages as apackages
from toolkit.analysis.artifacts import plain
from toolkit.engines.benchmark import verified_benchmarks

PRODUCER = "toolkit/analysis/decision_tests.py"
DIR = os.path.join("models", "decision_tests")
MAX_SCALE = 5.0
ACHIEVED_RTOL = 1e-9


def _threshold(A) -> float:
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "thresholds.yaml")) as f:
        default = yaml.safe_load(f)["decision_tests"]["share_threshold"]
    return float(A.spec["analysis"].get("share_threshold", default))


def _lowers_only_unchosen(ben0, ben, plan) -> bool:
    for i in ben0:
        for k, v in ben0[i].items():
            if ben[i][k] != v and (ben[i][k] > v or plan[i] == k):
                return False
    return True


def run_all(A, z0, out0, ben0, cost0, plan, uq_data, run_dir) -> list[dict]:
    os.makedirs(os.path.join(run_dir, DIR), exist_ok=True)
    out = []
    for dt in list(A.spec["analysis"].get("decision_tests") or []) + prior_range_tests(A):
        rec = run_one(A, dt, z0, ben0, cost0, plan, uq_data, out0)
        if dt.get("automatic"):
            rec["automatic"] = True
        p = os.path.join(run_dir, DIR, f"{dt['id']}.yaml")
        if rec.get("status") == "not_run":
            if os.path.exists(p):
                os.remove(p)            # no stale result file from an earlier run
            rec["path"] = None
        else:
            with open(p, "w") as f:
                yaml.safe_dump(plain(rec), f, sort_keys=False, width=120)
            rec["path"] = os.path.relpath(p, run_dir)
        out.append(rec)
    return out


PRIOR_RANGE_PREFIX = "prior_range_"


def prior_range_tests(A) -> list[dict]:
    """The automatic prior_range tests: every drawn prior is prior-dominated (the calibration does not condition on
    it), so each gets one (v2d note §3.2)."""
    return [{"id": f"{PRIOR_RANGE_PREFIX}{k}", "type": "prior_range", "parameter": k, "values": [p.lo, p.hi],
             "automatic": True, "finding": f"decision_test:{PRIOR_RANGE_PREFIX}{k}",
             "text": f"Does the plan change when {k} is at either end of its declared range?",
             "source": p.source} for k, p in A.pr.items()]


def _not_run(A, dt, why, extra=None) -> dict:
    return {"status": "not_run", "test_id": dt["id"], "type": dt["type"], "question": dt.get("text", ""),
            "statement": f"This test was not run: {why}.", "reason": why, "can_move_plan": None,
            "decision_changes": None, "share_units_changed": None, "share_threshold": _threshold(A),
            "produced_by": "harness", "producer": PRODUCER, **(extra or {})}


def run_one(A, dt, z0, ben0, cost0, plan, uq_data, out0=None) -> dict:
    t = dt["type"]
    thr = _threshold(A)
    evs = {}                       # model corrections per tested value (Codex r2 P1-3)
    extra, rejected = {}, []
    if t == "interaction_rescale":
        r = _interaction(A, dt, ben0, cost0, plan, out0)
        if r.get("not_run"):
            return _not_run(A, dt, r["not_run"], r.get("info"))
        varied, cases, lowers, extra, rejected = r["varied"], r["cases"], r["lowers"], r["extra"], r["rejected"]
    elif t in ("parameter_value", "prior_range"):
        p = dt["parameter"]
        if A.model.kind == "emulator" and p not in A.dr:
            return _not_run(A, dt, f"{p} is not an emulator input; it needs engine runs (direct evaluation), or a "
                                   "published prior so it enters the emulator design")
        varied = (f"engine parameter {p} set to each end of its declared prior range ({dt.get('source')})"
                  if t == "prior_range" else f"engine parameter {p} set to each tested value")
        cases, lowers = [], []
        vals = list(dt["values"])
        if A.model.kind == "emulator":
            # an emulator answer outside its design box is an extrapolation (and the plan guard would block the whole
            # analysis): such a value is refused, with the box; toolkit/analysis/batch.py widens the box to span the
            # spec's own parameter_value test values
            j = A.model.input_names.index(p)
            box = [float(A.model.dom_lo[j]), float(A.model.dom_hi[j])]
            tol = 1e-9 * max(box[1] - box[0], 1.0)
            rejected = [{"value": v, "design_box": box} for v in vals if not box[0] - tol <= float(v) <= box[1] + tol]
            vals = [v for v in vals if box[0] - tol <= float(v) <= box[1] + tol]
            if not vals:
                return _not_run(A, dt, f"every value of {p} is outside the emulator design box {box} (an emulator "
                                       "answer there would be an extrapolation); rebuild the batch so the design spans "
                                       "the test's values", {"rejected_values": rejected})
        for v in vals:
            theta = dict(A.theta0, **{p: float(v)})
            if A.method == "emulator_inversion":
                cz = A.calibrate(theta)
                zs = {i: x[0] for i, x in cz.items()}
                extra[v] = {"calibration_clamped_units": sum(bool(x[1]) for x in cz.values())}   # Codex r1 P1-3
            else:
                zs = z0
            _, ben, cost = A.evaluate(theta, zs)
            evs[v] = list(A.last_events)
            same_cost = all(abs(cost[i][k] - cost0[i][k]) <= 1e-9 * max(1.0, abs(cost0[i][k])) for i in A.ids for k in A.pk)
            lowers.append(same_cost and _lowers_only_unchosen(ben0, ben, plan))
            cases.append((v, ben, cost, None, None))
    elif t == "group_rule":
        a = copy.deepcopy(A.alloc)
        rules = dict(a.get("group_rules") or {})
        if dt.get("add"):
            add = dict(dt["add"])
            rules[add.pop("id", dt["id"])] = add
            varied = f"group rule added on {add.get('by')} for {', '.join(map(str, add.get('components') or []))}"
        else:
            rules.pop(dt["rule"], None)
            varied = f"group rule {dt['rule']} removed"
        a["group_rules"] = rules
        if not rules:
            a.pop("group_rules")
        feas = apackages.feasibility(a, A.spec.units())
        cases = [("with" if dt.get("add") else "without", ben0, cost0, None, feas)]
        lowers = [False]
    elif t == "envelope":
        varied = "the envelope set to each tested value"
        fixed = sum(float(v) for v in (A.spec["constraints"].get("fixed_costs_usd") or {}).values())
        cases = [(v, ben0, cost0, float(v) - fixed, None) for v in dt["values"]]
        lowers = [False] * len(cases)
    else:
        raise ValueError(f"decision test {dt.get('id')}: unknown type {t}")
    results = []
    for (v, ben, cost, budget, feas), low in zip(cases, lowers):
        sol = A.solve(ben, cost, budget=budget, feas=feas)
        ch = sol["choice"]
        A.guard(f"decision test {dt['id']} at {v}", [plan, ch], events=evs.get(v, []))
        n_changed = sum(ch[i] != plan[i] for i in A.ids)
        results.append({"value": v, "units_changed": n_changed, "share_units_changed": n_changed / len(A.ids),
                        "objective": sol["objective"], "point_plan_objective_under_test":
                            sum(ben[i][plan[i]] for i in A.ids), "recommendation": A.mix_text(ch),
                        "provably_unchanged": bool(low), **(extra.get(v) or {})})
    worst = max(results, key=lambda r: r["share_units_changed"])
    share = worst["share_units_changed"]
    comps = set(dt.get("components") or [])
    in_draws = sorted(comps & set(uq_data.get("components_in_any_draw_plan") or [])) if comps else None
    in_plan = sum(bool(A.pk[plan[i]] & comps) for i in A.ids) if comps else None
    if all(r["provably_unchanged"] for r in results):
        stmt = ("This test cannot move the plan: it only lowers the benefit of packages that no unit receives in the "
                "point plan, so the point plan stays optimal")
        if comps:
            stmt += (f"; {', '.join(sorted(comps))} is in {'some' if in_plan else 'no'} unit of the point plan and in "
                     f"{'some' if in_draws else 'none'} of the re-optimised uncertainty draws")
        can_move = False
    else:
        stmt = "This test can move the plan: it was re-solved for each value"
        can_move = True
    if rejected:
        stmt += "; some requested values could not be reached and were rejected"
    if any(r.get("calibration_clamped_units") for r in results):
        stmt += ("; at some tested values the calibration clamped at its range for some units, so those units do not "
                 "match their targets there (calibration_clamped_units per value)")
    finding = dt.get("finding") or f"decision_test:{dt['id']}"
    rec = {"statement": stmt + ".", "status": "run", "can_move_plan": can_move, "finding": finding,
           "test_id": dt["id"], "type": t, "question": dt.get("text", ""), "varied": varied,
           "criterion": f"the package changes in more than {thr:.0%} of units",
           "decision_changes": bool(share > thr), "share_units_changed": float(share), "share_threshold": thr,
           "recommendation": {"with": A.mix_text(plan), "without": worst["recommendation"]},
           "results": results, "rejected_values": rejected, "produced_by": "harness", "producer": PRODUCER}
    if comps:
        rec["relevance"] = {"components": sorted(comps), "units_with_component_point_plan": in_plan,
                            "components_in_any_draw_plan": in_draws}
    if t == "interaction_rescale":
        rec["engine_arm_or"], rec["engine_interaction"] = extra.get("_arm"), extra.get("_int")
        rec["arm_source"] = extra.get("_src")
    return rec


def _rescale(ratio: float, g: float) -> float:
    """The one transformation of the test (Codex r2 P1-5): an increment, as a ratio with and without the component, is
    rescaled on the log scale (ratio ** g). It is applied to the benchmark's odds ratio (a11 / a10) to solve and verify
    the target interaction, and to each unit's outcome ratio (package / package without the component) to change the
    allocation, so the two cannot disagree on the scale."""
    return ratio ** g


def _interaction(A, dt, ben0, cost0, plan, out0) -> dict:
    rows, why = verified_benchmarks(A.eng)
    if why:
        return {"not_run": f"the engine's benchmark arm ratios are not verified ({why})"}
    b = {r.get("id"): r for r in rows}.get(dt.get("benchmark"))
    if not b or not b.get("arm_or"):
        return {"not_run": f"benchmark {dt.get('benchmark')} with arm odds ratios is not in the verified results"}
    arm = {k: float(np.exp(np.mean([np.log(x[k]) for x in b["arm_or"]]))) for k in ("a11", "a10", "a01")}
    eng_int = arm["a11"] / (arm["a10"] * arm["a01"])
    r_inc = arm["a11"] / arm["a10"]               # the component's increment on top of the other, as an odds ratio
    if not r_inc < 1:
        return {"not_run": "in the benchmark setting the component adds nothing on top of the other, so no rescaling of "
                           "its increment can set the interaction", "info": {"engine_arm_or": arm}}
    inter = lambda g: arm["a10"] * _rescale(r_inc, g) / (arm["a10"] * arm["a01"])  # noqa: E731
    comp, with_any = set(dt["components"]), set(dt["with_any"])
    cases, lowers, rejected = [], [], []
    extra = {"_arm": arm, "_int": eng_int,
             "_src": f"verified benchmark results ({dt.get('benchmark')}), toolkit/engines/benchmark.py"}
    lo_reach, hi_reach = inter(MAX_SCALE), inter(0.0)
    o = A.primary
    for v in dt["values"]:
        g = math.log(v * arm["a01"]) / math.log(r_inc)
        if not 0.0 <= g <= MAX_SCALE:
            rejected.append({"value": v, "scale_needed": g, "reachable_interaction": [lo_reach, hi_reach]})
            continue
        achieved = inter(g)
        if abs(achieved - v) > ACHIEVED_RTOL * abs(v):
            raise RuntimeError(f"decision test {dt['id']}: achieved interaction {achieved} != requested {v}")
        ben = {}
        for i in A.ids:
            ben[i] = {}
            y0 = out0[i]["y"][A.comp][o]
            for k, cs in A.pk.items():
                if comp <= cs and cs & with_any:
                    base = next(n for n, c2 in A.pk.items() if c2 == cs - comp)
                    yb, yk = out0[i]["y"][base][o], out0[i]["y"][k][o]
                    if yb <= 0 or yk <= 0:
                        ben[i][k] = ben0[i][k]      # nothing to rescale (no outcome left)
                        continue
                    yk_new = yb * _rescale(yk / yb, g)
                    ben[i][k] = A.dfac * (y0 - yk_new)
                else:
                    ben[i][k] = ben0[i][k]
        cases.append((v, ben, None, None, None))
        lowers.append(_lowers_only_unchosen(ben0, ben, plan))
        extra[v] = {"increment_scale": g, "achieved_interaction": achieved}
    if not cases:
        return {"not_run": "no requested interaction can be reached by rescaling the increment within its allowed range "
                           "(the engine's reachable interval is in the test's info)",
                "info": {"engine_arm_or": arm, "engine_interaction": eng_int, "rejected_values": rejected,
                         "reachable_interaction": [lo_reach, hi_reach]}}
    cases = [(v, ben, cost0, b_, f_) for (v, ben, _c, b_, f_) in cases]
    varied = (f"the increment of {sorted(comp)} given any of {sorted(with_any)} rescaled on the log scale so the "
              f"engine's interaction odds ratio in the {dt.get('benchmark')} setting equals each tested value")
    return {"varied": varied, "cases": cases, "lowers": lowers, "extra": extra, "rejected": rejected}

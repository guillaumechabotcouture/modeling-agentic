def _table_sha(rows) -> str:
    """sha256 of a units table as CSV (its own column order, '\\n' line ends): the modified table's identity."""
    import csv
    import hashlib
    import io
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=list(rows[0]) if rows else [], lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    return hashlib.sha256(buf.getvalue().encode()).hexdigest()


def _num_or_none(x):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return None
    return v if math.isfinite(v) and not isinstance(x, bool) else None


def plan_unit_attribute(spec, dt, card, kind=None, features_box=None) -> dict:
    """The cases a unit_attribute test runs, without running the engine: each a copy of the units table as
    Spec.units() reads it, with column `column` set (values), multiplied (scale) or taken per unit from a table in the
    run directory (set_from) for the listed units (default all). Refused (status not_run, why): an unknown column; a
    column that feeds no engine unit attribute (decision_units.engine_attributes), or only the calibrated one (the
    calibration overrides it per unit); unit ids not in the table; no declared domain (EngineCard.valid_ranges of the
    attribute) or a case outside it; on the emulator path (`kind` emulator) a column that reaches no emulator feature or
    a case outside the design box of a feature (`features_box`, when known); a test whose every case is an identity."""
    def no(why, rejected=()):
        return {"status": "not_run", "why": why, "perturbations": [], "rejected": list(rejected)}
    ua = dt.get("unit_attribute")
    if not isinstance(ua, dict) or not ua.get("column"):
        return no("give unit_attribute: {column, units: [ids] | all, values: [..] | scale: [..] | set_from: <table>}")
    col = str(ua["column"])
    base = spec.units()
    if not base or col not in base[0]:
        return no(f"{col!r} is not a column of the units table")
    ea = (spec.raw.get("decision_units") or {}).get("engine_attributes") or {}
    attrs = []
    for a, m in ea.items():
        if not isinstance(m, dict):
            continue
        cs = [m["column"]] if "column" in m else list((m.get("columns") or {}).values()) \
            if isinstance(m.get("columns"), dict) else list(m.get("columns") or [])
        if col in cs:
            if "split" in m:
                return no(f"column {col} holds a list (split) for attribute {a}; a test varies a numeric column")
            attrs.append(a)
    if not attrs:
        return no(f"column {col} feeds no engine unit attribute (decision_units.engine_attributes binds none to it), "
                  "so changing it cannot reach the engine")
    cal = spec.raw.get("calibration") or {}
    if cal.get("method") not in (None, "none") and cal.get("attribute") in attrs:
        return no(f"column {col} feeds {cal['attribute']}, which the calibration sets per unit, so the engine never "
                  "reads the column")
    doms = {a: (card.valid_ranges or {}).get(a) for a in attrs}
    if any(not (isinstance(d, (list, tuple)) and len(d) == 2) for d in doms.values()):
        return no(f"the engine card declares no valid range for {sorted(a for a, d in doms.items() if not d)} "
                  "(EngineCard.valid_ranges), so the column has no declared domain to check the tested values against")
    lo, hi = max(float(d[0]) for d in doms.values()), min(float(d[1]) for d in doms.values())
    uid = spec.uid
    ids = [str(u[uid]) for u in base]
    sel = ua.get("units", "all")
    if sel == "all":
        chosen = list(ids)
    elif isinstance(sel, list) and sel:
        unknown = [str(x) for x in sel if str(x) not in ids]
        if unknown:
            return no(f"units {unknown} are not in the units table")
        chosen = [str(x) for x in sel]
    else:
        return no("units: `all` or a non-empty list of unit ids")
    modes = [k for k in ("values", "scale", "set_from") if k in ua]
    if len(modes) != 1:
        return no(f"give exactly one of values, scale or set_from (got {modes or 'none'})")
    mode = modes[0]
    old = {}
    for i, u in zip(ids, base):
        old[i] = _num_or_none(u[col])
    if any(old[i] is None for i in chosen):
        return no(f"column {col} is not a finite number in every selected unit")
    cases, inputs = [], {}
    if mode in ("values", "scale"):
        xs = ua[mode]
        if not isinstance(xs, list) or not xs or any(_num_or_none(x) is None for x in xs):
            return no(f"{mode}: a non-empty list of numbers")
        for x in xs:
            cases.append((float(x), {i: float(x) if mode == "values" else old[i] * float(x) for i in chosen}))
    else:
        import csv
        rel = str(ua["set_from"])
        root = os.path.realpath(spec.base)
        p = os.path.realpath(spec.resolve(rel))
        if os.path.isabs(rel) or os.path.commonpath([root, p]) != root:
            return no(f"set_from {rel} must be a table inside the run directory (a relative path)")
        try:
            with open(p, newline="", encoding="utf-8") as f:
                rows = list(csv.DictReader(f))
            with open(p, "rb") as f:
                import hashlib
                inputs[rel] = hashlib.sha256(f.read()).hexdigest()
        except OSError as e:
            return no(f"set_from {rel} cannot be read ({type(e).__name__})")
        if not rows or uid not in rows[0] or col not in rows[0]:
            return no(f"set_from {rel}: give columns {uid} and {col}")
        new = {str(r[uid]): _num_or_none(r[col]) for r in rows}
        unknown = [i for i in new if i not in ids]
        if unknown or any(v is None for v in new.values()):
            return no(f"set_from {rel}: units {unknown} are not in the units table" if unknown else
                      f"set_from {rel}: {col} is not a finite number in every row")
        if sel != "all":
            new = {i: v for i, v in new.items() if i in chosen}
        cases.append((rel, new))
    feats = []
    if kind == "emulator":
        from toolkit.analysis import features as FT
        feats = [FT.name(f) for f in FT.declared(spec.raw)
                 if f == col or (isinstance(f, dict) and f.get("attribute") in attrs)]
        if not feats:
            return no(f"column {col} is not an emulator input (analysis.emulator.features names neither it nor "
                      f"{attrs}), so the emulator's answer cannot respond to it; declare a feature or use direct "
                      "evaluation")
    tol = 1e-9 * max(hi - lo, 1.0)
    perts, rejected = [], []
    for label, new in cases:
        out_ = sorted(i for i, v in new.items() if not lo - tol <= v <= hi + tol)
        if out_:
            rejected.append({"value": label, "units_outside": out_, "declared_domain": [lo, hi]})
            continue
        rows = [dict(u, **{col: repr(float(new[i]))}) if i in new else dict(u) for i, u in zip(ids, base)]
        changed = [i for i in ids if i in new and abs(new[i] - old[i]) > 1e-12 * max(1.0, abs(old[i]))]
        if kind == "emulator" and features_box and changed:
            from toolkit.analysis import features as FT
            names = [FT.name(f) for f in FT.declared(spec.raw)]
            by = dict(zip(ids, rows))
            far = [i for i in changed for nm, v in zip(names, FT.vector(spec, by[i])) if nm in features_box
                   and not features_box[nm][0] - tol <= v <= features_box[nm][1] + tol]
            if far:
                rejected.append({"value": label, "units_outside": sorted(set(far)),
                                 "design_box": {nm: list(features_box[nm]) for nm in feats if nm in features_box}})
                continue
        perts.append({"value": label, "units_changed": changed, "table_sha256": _table_sha(rows),
                      "identity": not changed, "_rows": rows})
    if not perts:
        return no(f"every case puts some unit outside the column's declared domain [{lo:g}, {hi:g}] or the emulator's "
                  "design box (the rejected cases name the units)", rejected)
    if all(x["identity"] for x in perts):
        return no("every case leaves every unit's value unchanged (an identity): the test varies nothing", rejected)
    info = {"column": col, "attributes": sorted(attrs), "mode": mode, "units": sel if sel == "all" else chosen,
            "declared_domain": [lo, hi], "base_table_sha256": _table_sha([dict(u) for u in base]), "inputs": inputs,
            "emulator_features": feats}
    return {"status": "runs", "why": "", "perturbations": perts, "rejected": rejected, "info": info}


def units_table(A, rows):
    """A context in which the analysis reads `rows` as its units table: the spec's own reader cache (Spec.units) holds
    them, and every per-unit view built from it (analysis rows, feasibility, the model's rows, engine attributes and
    emulator features) is rebuilt by the functions that built it at the start (Spec.unit_attributes, features.vector,
    packages.feasibility); all restored on exit."""
    import contextlib
    from toolkit.alloc import packages as apackages
    from toolkit.analysis import features as FT

    @contextlib.contextmanager
    def ctx():
        sp, m = A.spec, A.model
        saved = {"u": sp._units, "by": A.by_id, "feas": A.feas, "mby": getattr(m, "by_id", None),
                 "attrs": getattr(m, "attrs", None), "fv": getattr(m, "fv", None)}
        try:
            sp._units = rows
            A.by_id = {str(u[sp.uid]): u for u in rows}
            A.feas = apackages.feasibility(A.alloc, rows)
            if saved["mby"] is not None:
                m.by_id = dict(A.by_id)
            if saved["attrs"] is not None:
                m.attrs = {i: sp.unit_attributes(u) for i, u in A.by_id.items()}
            if saved["fv"] is not None:
                m.fv = {i: FT.vector(sp, u) for i, u in A.by_id.items()}
            yield
        finally:
            sp._units, A.by_id, A.feas = saved["u"], saved["by"], saved["feas"]
            for k, attr in (("mby", "by_id"), ("attrs", "attrs"), ("fv", "fv")):
                if saved[k] is not None:
                    setattr(m, attr, saved[k])
    return ctx()


def _unit_attribute(A, dt, z0, ben0, cost0, plan) -> dict:
    pl = plan_test(A.spec, dt, runtime_evidence(A))
    if pl["status"] != "runs":
        return {"not_run": pl["why"], "info": {"rejected_values": pl["rejected"]} if pl["rejected"] else None}
    info = pl["info"]
    recal = A.method == "emulator_inversion" and A.joint is None
    cases, lowers, extra, evs = [], [], {"_ident": [bool(x["identity"]) for x in pl["perturbations"]]}, {}
    for pt in pl["perturbations"]:
        v = pt["value"]
        with units_table(A, pt["_rows"]):
            zs = z0
            if recal:       # the calibration redone on the modified table, as a parameter_value test redoes it
                cz = A.calibrate(A.theta0)
                zs = {i: x[0] for i, x in cz.items()}
                extra[v] = {"calibration_clamped_units": sum(bool(x[1]) for x in cz.values())}
            _, ben, cost = A.evaluate(A.theta0, zs)
            evs[v] = list(A.last_events)
            feas = A.feas
        same_cost = all(abs(cost[i][k] - cost0[i][k]) <= 1e-9 * max(1.0, abs(cost0[i][k])) for i in A.ids for k in A.pk)
        lowers.append(same_cost and _lowers_only_unchosen(ben0, ben, plan))
        cases.append((v, ben, cost, None, feas))
    how = {"values": "set to each tested value", "scale": "multiplied by each tested factor",
           "set_from": "set per unit from the table named"}[info["mode"]]
    varied = (f"units-table column {info['column']} (engine unit attribute {', '.join(info['attributes'])}) {how} in "
              f"{'every unit' if info['units'] == 'all' else 'the listed units'}; the calibration "
              + ("redone on the modified table" if recal else "held at the headline values"))
    rec = dict(info, calibration="redone" if recal else "held", cases=[
        {k: x[k] for k in ("value", "units_changed", "table_sha256", "identity")} for x in pl["perturbations"]],
        rejected=pl["rejected"])
    return {"varied": varied, "cases": cases, "lowers": lowers, "extra": extra, "rejected": pl["rejected"],
            "evs": evs, "record": rec}


def _not_run(A, dt, why, extra=None) -> dict:
    return {"status": "not_run", "test_id": dt["id"], "type": dt["type"], "question": dt.get("text", ""),
            "statement": f"This test was not run: {why}.", "reason": why, "can_move_plan": None,
            "decision_changes": None, "triggered_by": None, "share_units_changed": None, "share_threshold": _threshold(A),
            "produced_by": "harness", "producer": PRODUCER, **(extra or {})}


def run_one(A, dt, z0, ben0, cost0, plan, uq_data, out0=None) -> dict:
    t = dt["type"]
    thr = _threshold(A)
    sv = None                      # a parameter_value test on a spec-declared engine parameter value
    evs = {}                       # model corrections per tested value (Codex r2 P1-3)
    extra, rejected = {}, []
    if t == "interaction_rescale":
        r = _interaction(A, dt, ben0, cost0, plan, out0)
        if r.get("not_run"):
            return _not_run(A, dt, r["not_run"], r.get("info"))
        varied, cases, lowers, extra, rejected = r["varied"], r["cases"], r["lowers"], r["extra"], r["rejected"]
    elif t == "unit_attribute":
        ur = _unit_attribute(A, dt, z0, ben0, cost0, plan)
        if ur.get("not_run"):
            return _not_run(A, dt, ur["not_run"], ur.get("info"))
        varied, cases, lowers, extra, rejected, evs = (ur[k] for k in ("varied", "cases", "lowers", "extra", "rejected",
                                                                       "evs"))
        extra["_ua"] = ur["record"]
    elif t == "scenario_excluded":
        return _not_run(A, dt, f"the spec holds the scenario value {dt['parameter']} fixed by name: {dt['reason']}",
                        {"parameter": dt["parameter"]})
    elif t in ("parameter_value", "prior_range", "fitted_range"):
        p = dt["parameter"]
        pl = plan_test(A.spec, dt, runtime_evidence(A))
        if pl["status"] != "runs":
            return _not_run(A, dt, pl["why"], {"rejected_values": pl["rejected"]} if pl["rejected"] else None)
        varied = (f"engine parameter {p} set to each end of its declared prior range ({dt.get('source')})"
                  if t == "prior_range" else
                  f"fitted engine parameter {p} set to each end of its {'jointly calibrated' if dt.get('joint') else 'fitted'}"
                  " range" if t == "fitted_range" else f"engine parameter {p} set to each tested value")
        cases, lowers = [], []
        vals, rejected = [x["value"] for x in pl["perturbations"]], pl["rejected"]
        extra["_ident"] = [bool(x.get("identity")) for x in pl["perturbations"]]
        from toolkit.spec import engine_parameters as PV
        if t == "parameter_value" and p in PV.values(A.spec):   # the headline runs at the spec value: record the card
            # value it replaces
            cv = float(next(x.value for x in A.eng.parameters() if x.name == p))
            sv = {"value": PV.values(A.spec)[p], "card_value": cv,
                  "card_value_tested": any(abs(float(v) - cv) <= 1e-9 * max(1.0, abs(cv)) for v in vals)}
        # an emulator answer outside its design box is an extrapolation: plan_test() refused such values, with the box;
        # toolkit/analysis/batch.py widens the box to span the spec's own parameter_value test values
        for v in vals:
            theta = dict(A.theta0, **{p: float(v)})
            if A.method == "emulator_inversion":
                cz = A.calibrate(theta)
                zs = {i: x[0] for i, x in cz.items()}
                extra[v] = {"calibration_clamped_units": sum(bool(x[1]) for x in cz.values())}   # Codex r1 P1-3
            elif A.method == "posterior" and (p in (A.lik or {}).get("params", []) or p.startswith("z:")
                                              or p in (A.lik or {}).get("nuisance", [])):
                from toolkit.analysis import calibration as C
                if p.startswith("z:"):     # a unit attribute at each end of its range, the calibration redone
                    fit = C.fit_posterior_panel(A.spec, A.model, fixed_z={p[2:]: float(v)}, sample_it=False)
                    zs = dict(fit["z"], **{p[2:]: float(v)})
                else:                      # an engine parameter, or a source's bias parameter (never an engine input)
                    fit = C.fit_posterior_panel(A.spec, A.model, fixed_params={p: float(v)}, sample_it=False)
                    zs = dict(fit["z"])
                zs = {i: zs.get(i, fit["fixed_z"].get(i)) for i in A.ids}
                theta = dict({k: x for k, x in A.theta0.items() if k != p or k in fit["theta"]}, **fit["theta"])
            else:
                zs = z0
            _, ben, cost = A.evaluate(theta, zs)
            evs[v] = list(A.last_events)
            same_cost = all(abs(cost[i][k] - cost0[i][k]) <= 1e-9 * max(1.0, abs(cost0[i][k])) for i in A.ids for k in A.pk)
            lowers.append(same_cost and _lowers_only_unchosen(ben0, ben, plan))
            cases.append((v, ben, cost, None, None))
    elif t == "anchor_range":
        varied = (f"the external estimates of anchors {', '.join(dt['anchors'])} set together to the 2.5% and 97.5% "
                  "ends of their published intervals")
        cases, lowers = [], []
        for v in dt["values"]:
            _, ben, cost = A.evaluate(A.theta0, z0, sampled=dt["ends"][v])
            evs[v] = list(A.last_events)
            cases.append((v, ben, cost, None, None))
            lowers.append(False)
    elif t == "group_rule":
        from toolkit.analysis import variants as V
        a = copy.deepcopy(V.base_alloc(A))        # the signed rules; a headline variant's rule is joined below
        rules = dict(a.get("group_rules") or {})
        if dt.get("add"):
            add = dict(dt["add"])
            rules[add.pop("id", dt["id"])] = add
            varied = f"group rule added on {add.get('by')} for {', '.join(map(str, add.get('components') or []))}"
        else:
            rules.pop(dt["rule"], None)
            varied = f"group rule {dt['rule']} removed"
        a["group_rules"] = rules
        if not rules:
            a.pop("group_rules")
        feas = V.carry(A, a)      # F6 S1-6: a headline variant's rule, which the test can neither replace nor remove
        cases = [("with" if dt.get("add") else "without", ben0, cost0, None, feas)]
        lowers = [False]
    elif t == "envelope":
        varied = "the envelope set to each tested value"
        fixed = sum(float(v) for v in (A.spec["constraints"].get("fixed_costs_usd") or {}).values())
        A.spec.packages()
        bound = getattr(A.spec, "prune_budget", None)
        if bound is not None and any(float(v) - fixed > bound * (1 + 1e-12) for v in dt["values"]):
            return _not_run(A, dt, "an envelope above the declared one, and the packages were generated within the "
                                   "declared envelope (options.packages.within_envelope): drop within_envelope to "
                                   "test larger envelopes")
        # F6 S1-1b: the reserve policy holds at each envelope (the same fraction held back), so the declared envelope
        # reproduces the headline plan
        cases = [(v, ben0, cost0, A.planned(float(v) - fixed), None) for v in dt["values"]]
        lowers = [False] * len(cases)
    elif t == "cost_items":
        mult = {k: float(m) for k, m in dt["multipliers"].items()}      # the ids as the cost items declare them
        varied = "the unit costs of the listed cost items multiplied together (cost_multipliers)"
        _, ben, cost = A.evaluate(A.theta0, z0, cost_mult=mult)
        evs["case"] = list(A.last_events)
        extra["case"] = {"cost_multipliers": mult}
        cases, lowers = [("case", ben, cost, None, None)], [False]
    else:
        raise ValueError(f"decision test {dt.get('id')}: unknown type {t}")
    results = []
    for (v, ben, cost, budget, feas), low in zip(cases, lowers):
        try:
            sol = A.solve(ben, cost, budget=budget, feas=feas)
        except RuntimeError as e:
            if t != "cost_items" or str(e).strip() != "optimizer status infeasible":
                raise
            # Codex r1: the price case has no affordable plan; the record keeps the prices and says why
            return _not_run(A, dt, "at these prices no allocation that meets the constraints fits the budget the plan "
                                   "is solved within (the solver proves it), so there is no re-solved plan to compare "
                                   "with the point plan", {"cost_multipliers": dict(mult)})
        ch = sol["choice"]
        A.guard(f"decision test {dt['id']} at {v}", [plan, ch], events=evs.get(v, []))
        # F6 S1-5: what moves beside the share (regret, population, dollars by component, units by group)
        # (the point plan judged under the test's costs, feasibility and planning budget: Codex r1 P2-1)
        bchg = {c: max((abs(float(ben[i][k]) - float(ben0[i][k])) for i in A.ids for k in A.pk if c in A.pk[k]),
                       default=0.0) for c in (A.spec["options"].get("components") or {})}
        results.append({"value": v, **MV.summarise(A, plan, ch, ben, cost, sol["objective"], budget=budget, feas=feas),
                        "benefit_change": bchg,
                        "objective": sol["objective"], "recommendation": A.mix_text(ch),
                        "provably_unchanged": bool(low), **(extra.get(v) or {})})
    worst = max(results, key=lambda r: r["share_units_changed"])
    th = MV.thresholds(A.spec["analysis"])
    agg = MV.aggregate(results)       # each criterion's worst value, with its own breakdown (Codex r1 P2-3)
    comps = set(dt.get("components") or [])
    in_draws = sorted(comps & set(uq_data.get("components_in_any_draw_plan") or [])) if comps else None
    in_plan = sum(bool(A.pk[plan[i]] & comps) for i in A.ids) if comps else None
    if all(r["provably_unchanged"] for r in results):
        stmt = ("This test cannot move the plan: it only lowers the benefit of packages that no unit receives in the "
                "point plan, so the point plan stays optimal")
        if comps:
            stmt += (f"; {', '.join(sorted(comps))} is in {'some' if in_plan else 'no'} unit of the point plan and in "
                     f"{'some' if in_draws else 'none'} of the re-optimised uncertainty draws")
        can_move = False
    else:
        stmt = "This test can move the plan: it was re-solved for each value"
        can_move = True
    if sv:
        stmt += (f"; the headline uses the spec value of {dt['parameter']} (engine_parameters), and the engine card "
                 "value " + ("is one of the tested values" if sv["card_value_tested"]
                             else "is not among the tested values"))
    if rejected:
        stmt += "; some requested values could not be reached and were rejected"
    if any(r.get("calibration_clamped_units") for r in results):
        stmt += ("; at some tested values the calibration clamped at its range for some units, so those units do not "
                 "match their targets there (calibration_clamped_units per value)")
    finding = dt.get("finding") or f"decision_test:{dt['id']}"
    rec = {"statement": stmt + ".", "status": "run", "can_move_plan": can_move, "finding": finding,
           "test_id": dt["id"], "type": t, "question": dt.get("text", ""), "varied": varied,
           "criterion": (f"the package changes in more than {thr:.0%} of units, or keeping the point plan loses more "
                         f"than {th['regret']:.1%} of the re-optimised objective, or more than {th['dollars']:.0%} of "
                         "the allocatable budget is reallocated across units and components, or the point plan is "
                         "not feasible under the test"),
           **agg, "share_threshold": thr, "regret_threshold": th["regret"], "dollars_threshold": th["dollars"],
           "recommendation": {"with": A.mix_text(plan), "without": worst["recommendation"]},
           "results": results, "rejected_values": rejected, "produced_by": "harness", "producer": PRODUCER,
           # #215 round 4: the realised change in each component's benefit, and the packages a test had to skip
           "benefit_change": {c: max(float(r["benefit_change"].get(c, 0.0)) for r in results)
                              for c in (A.spec["options"].get("components") or {})},
           "missing_subtraction": list(extra.get("_missing") or []),
           "perturbation_identity": list(extra.get("_ident") or []),
           "benefit_change_by_package": {k: max(max((abs(float(c_[1][i][k]) - float(ben0[i][k])) for i in A.ids),
                                                    default=0.0) for c_ in cases) for k in A.pk},
           "package_components": {k: sorted(v) for k, v in A.pk.items()}}
    if sv:
        rec["spec_value"] = sv
    if t == "cost_items":
        rec["cost_multipliers"] = dict(extra["case"]["cost_multipliers"])
    if t == "unit_attribute":       # the column, the units changed and each modified table's sha256
        rec["unit_attribute"] = extra["_ua"]
    if comps:
        rec["relevance"] = {"components": sorted(comps), "units_with_component_point_plan": in_plan,
                            "components_in_any_draw_plan": in_draws}
    if t == "interaction_rescale":
        rec["engine_arm_or"], rec["engine_interaction"] = extra.get("_arm"), extra.get("_int")
        rec["arm_source"] = extra.get("_src")
        if extra.get("_inputs"):
            rec["arm_inputs"] = extra["_inputs"]
    return rec


def _rescale(ratio: float, g: float) -> float:
    """The one transformation of the test (Codex r2 P1-5): an increment, as a ratio with and without the component, is
    rescaled on the log scale (ratio ** g). It is applied to the benchmark's odds ratio (a11 / a10) to solve and verify
    the target interaction, and to each unit's outcome ratio (package / package without the component) to change the
    allocation, so the two cannot disagree on the scale."""
    return ratio ** g


def _interaction(A, dt, ben0, cost0, plan_, out0) -> dict:
    pl = plan_test(A.spec, dt, runtime_evidence(A))
    if pl["status"] != "runs":
        return {"not_run": pl["why"], "info": pl.get("info")}
    info = pl["info"]
    arm, eng_int = info["engine_arm_or"], info["engine_interaction"]
    comp = set(dt["components"])
    cases, lowers, rejected = [], [], pl["rejected"]
    extra = {"_arm": arm, "_int": eng_int, "_src": f"verified benchmark results ({dt.get('benchmark')}), {info['src']}",
             "_inputs": info["inputs"], "_missing": list(info.get("missing_subtraction") or []),
             "_ident": [bool(x.get("identity")) for x in pl["perturbations"]]}
    o = A.primary
    for pt in pl["perturbations"]:
        v, g = pt["value"], pt["scale"]
        if abs(pt["achieved"] - v) > ACHIEVED_RTOL * abs(v):
            raise RuntimeError(f"decision test {dt['id']}: achieved interaction {pt['achieved']} != requested {v}")
        ben = {}
        for i in A.ids:
            ben[i] = {}
            y0 = out0[i]["y"][A.comp][o]
            for k in A.pk:
                base = pt["packages"].get(k)
                if base is not None:
                    yb, yk = out0[i]["y"][base][o], out0[i]["y"][k][o]
                    if yb <= 0 or yk <= 0:
                        ben[i][k] = ben0[i][k]      # nothing to rescale (no outcome left)
                        continue
                    yk_new = yb * _rescale(yk / yb, g)
                    ben[i][k] = A.dfac * (y0 - yk_new)
                else:
                    ben[i][k] = ben0[i][k]
        cases.append((v, ben, None, None, None))
        lowers.append(_lowers_only_unchosen(ben0, ben, plan_))
        extra[v] = {"increment_scale": g, "achieved_interaction": pt["achieved"]}
    with_any = set(dt["with_any"])
    cases = [(v, ben, cost0, b_, f_) for (v, ben, _c, b_, f_) in cases]
    varied = (f"the increment of {sorted(comp)} given any of {sorted(with_any)} rescaled on the log scale so the "
              f"engine's interaction odds ratio in the {dt.get('benchmark')} setting equals each tested value")
    return {"varied": varied, "cases": cases, "lowers": lowers, "extra": extra, "rejected": rejected}

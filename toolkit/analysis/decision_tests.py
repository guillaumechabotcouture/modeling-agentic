def _outcome_ratio(A, dt, out0, ben0, cost0, plan, z0=None) -> dict:
    """F6 run 2, owner decision (DT13): each package holding `component` has its primary-outcome burden set to
    `value` times its counterpart's, the package with `reference` in the component's place (the trial's relative
    effect of one net type against another), for each value; benefits re-derived against the comparator, costs and
    every other package held, the plan re-solved. Emulator outputs only: nothing is evaluated anew. Not run when no
    package has a counterpart. A package holding `component` with no counterpart is held and disclosed (`unpaired`,
    the record's missing_subtraction; #248 P2-4)."""
    oc = dt["outcome_ratio"]
    c, ref = oc["component"], oc["reference"]
    from toolkit.analysis import outcome_adjust as OA   # Codex review of #251 P1-1, P1-4 (sign-off refuses these too)
    conflict = OA.dt_problems(oc, getattr(A, "adjust", None))
    if conflict:
        return {"not_run": "; ".join(conflict)}
    pairs, unpaired = {}, []
    for k, cs in A.pk.items():
        if c in cs and ref not in cs:
            kk = next((n for n, c2 in A.pk.items() if set(c2) == (set(cs) - {c}) | {ref}), None)
            if kk is not None:
                pairs[k] = kk
            else:
                unpaired.append(k)       # Codex review of #245 P2-4: disclosed, never claimed as tested
    if not pairs:
        return {"not_run": f"no package with {c} has a counterpart with {ref} in its place"}
    o = A.primary
    cases, lowers, check, by_value, evs = [], [], {}, {}, {}
    for v in oc["values"]:
        if v == "engine":       # F6 run 4 R3: the component's base adjustment removed (the engine's own effect)
            saved = A.adjust
            if not any(a["component"] == c for a in saved or []):
                return {"not_run": f"the value \"engine\" needs a base outcome adjustment of {c}"}
            A.adjust = [a for a in saved if a["component"] != c]
            try:
                _o, ben_e, _c = A.evaluate(A.theta0, z0)
                evs[v] = list(A.last_events)
            finally:
                A.adjust = saved
            ben = {i: dict(ben_e[i]) for i in A.ids}     # Codex review of #251 P1-1: the whole re-evaluation
        else:
            r = float(v)
            pev = list(getattr(A, "point_events", None) or [])     # Codex re-review of #251 P1-2: out0's corrections,
            evs[v] = pev + OA.derive_events(pev, pairs)             # and the counterparts' on the derived (r3 P1)
            ben = {i: dict(ben0[i]) for i in A.ids}
            for i in A.ids:
                y0 = out0[i]["y"][A.comp][o]
                for k, kk in pairs.items():
                    ben[i][k] = A.dfac * (y0 - r * out0[i]["y"][kk][o])
        if not check:
            check = {i: ben[i][next(iter(pairs))] for i in A.ids}
        by_value[str(v)] = {i: ben[i][next(iter(pairs))] for i in A.ids}
        cases.append((v, ben, cost0, None, None))
        lowers.append(_lowers_only_unchosen(ben0, ben, plan))
    unpaired.sort()
    return {"varied": f"the {o} of every package with {c} that has a counterpart set to each tested ratio times that "
                      f"of the same package with {ref} in its place"
                      + (f" ({len(unpaired)} without one held: {unpaired[:5]})" if unpaired else ""),
            "cases": cases, "lowers": lowers,
            "record": {"component": c, "reference": ref, "values": list(oc["values"]), "outcome": o, "pairs": pairs,
                       "unpaired": unpaired, "check": check, "check_by_value": by_value,
                       "base_adjustments": [a["id"] for a in getattr(A, "adjust", None) or []]}, "evs": evs, "unpaired": unpaired}


def burden_scale_refs(spec, bs) -> tuple[list[dict], list[str]]:
    """(the listed references, problems) of a burden_scale mapping, read through validation.burden's own loader:
    each listed id a reference of the file, kind estimated, role checked or report_only (an anchor already sets its
    group's level), and no unit in the groups of two listed references (a unit takes one factor). Shared by sign-off
    (toolkit/spec/schema.py) and the run."""
    from toolkit.analysis import burden as BV
    if BV.section(spec.raw) is None:
        return [], ["a burden_scale test needs validation.burden references (the external estimates it scales to)"]
    refs, bad = BV.load_references(spec)
    if bad:
        return [], [f"validation.burden: {b}" for b in bad[:3]]
    by = {r["id"]: r for r in refs}
    ids = bs.get("references")
    if not (isinstance(ids, list) and ids and len(set(map(str, ids))) == len(ids)):
        return [], ["burden_scale.references: distinct reference ids of validation.burden's file"]
    miss = [str(x) for x in ids if str(x) not in by]
    if miss:
        return [], [f"burden_scale.references: unknown reference id(s) {miss}"]
    rows = [by[str(x)] for x in ids]
    bad = [f"burden_scale.references: {r['id']} is {r['kind']}, {r['role']}: only an estimated checked or report-only "
           "row sets a scale" for r in rows if r["kind"] != "estimated" or r["role"] not in ("checked", "report_only")]
    bad += [f"burden_scale.references: {r['id']} has an age band and no model window: its value needs a new "
            "prediction, and the test reads the point outputs only (declare validation.burden.window)"
            for r in rows if r["age_band"] and not r["window"]]
    cfg, units, uid = BV.config(spec), spec.units(), spec["decision_units"]["id"]
    seen = {}
    for r in rows:
        col = r.get("group_by") or cfg["group"]
        for u in units:
            if r["group"] == "*" or str(u.get(col)) == r["group"]:
                if str(u[uid]) in seen and seen[str(u[uid])] != r["id"]:
                    bad.append(f"burden_scale.references: unit {u[uid]} is in the groups of more than one listed "
                               f"reference ({seen[str(u[uid])]}, {r['id']})")
                    return rows, bad
                seen[str(u[uid])] = r["id"]
    return rows, bad


def _burden_scale(A, dt, z0, out0, ben0, cost0) -> dict:
    """F6 run 3, owner decision D-c (a declared departure from principle 3, baseline burden from external estimates):
    for each listed validation.burden reference, every package's outcomes in the units of its group are multiplied by
    factor^share, factor = the reference's value / the model's point value for that row (the comparison
    burden_validation reports, here from the point outputs). The relative reductions stay the engine's; benefits,
    which are differences of burdens, scale with them. Costs and every other unit are held, the plan re-solved, and
    nothing is evaluated anew. A reference whose outcome, age band or window differs from the objective's applies its
    ratio to the objective's outcome: an assumption the record states. Every re-solved plan is guarded with the point
    evaluation's model corrections (Analysis.point_events, set by run.py). Not run when a listed row cannot be read,
    its model value or factor is not finite and positive, or the point corrections are not recorded."""
    from toolkit.analysis import burden as BV
    bs = dt.get("burden_scale") or {}
    rows, bad = burden_scale_refs(A.spec, bs)
    if bad:
        return {"not_run": "; ".join(bad)}
    ev0 = getattr(A, "point_events", None)    # Codex review of #246 P1-1: the point tables' own corrections
    if ev0 is None:
        return {"not_run": "the point evaluation's model corrections are not recorded (Analysis.point_events), so the "
                           "re-solved plans could not be guarded"}
    cfg = BV.config(A.spec)
    arm = cfg["arm"]
    refs, unit_f, firsts = {}, {}, set()
    for r in rows:
        m = BV._value(A, cfg, r, out0, arm)
        f = float(r["value"]) / float(m) if m is not None and math.isfinite(float(m)) and float(m) > 0 else None
        if f is None or not (math.isfinite(f) and f > 0):     # Codex review of #246 P1-2
            return {"not_run": f"reference {r['id']}: its model value ({m}) or its value ({r['value']}) is not finite "
                               "and positive"}
        us = BV._members(A, r.get("group_by") or cfg["group"], r["group"])
        unit_f.update({i: f for i in us})
        firsts.update(us[:1])
        refs[r["id"]] = {"group": r["group"], "group_by": r.get("group_by") or cfg["group"], "units": len(us),
                         "outcome": r["outcome"], "age_band": r["age_band"], "value": float(r["value"]),
                         "model": float(m), "factor": f, "window": r["window"]}
    shares = [float(s) for s in bs["shares"]]
    cases, lowers = [], []
    for s in shares:
        ben = {i: {k: float(v) * unit_f.get(i, 1.0) ** s for k, v in ben0[i].items()} for i in A.ids}
        cases.append((s, ben, cost0, None, None))
        lowers.append(False)
    top = cases[max(range(len(shares)), key=lambda n: shares[n])][1]
    held = next((i for i in A.ids if i not in unit_f), None)
    check = {i: dict(top[i]) for i in sorted(firsts | ({held} if held is not None else set()))}
    o = A.primary
    mism = sorted({x["id"] for x in rows if x["outcome"] != o or x["age_band"] or x["window"]})
    return {"varied": "every package's outcomes in the units of each listed external reference's group scaled by "
                      "(reference / model)^share, the engine's relative reductions kept", "cases": cases,
            "lowers": lowers,
            "record": {"references": refs, "shares": shares, "objective_outcome": o, "arm": arm, "check": check,
                       "assumption": (f"the ratio of {', '.join(mism)} (another outcome, an age band or another "
                                      f"window than the objective's) is applied to every package's {o} over the "
                                      "objective's horizon") if mism else None},
            "evs": {s: list(ev0) for s in shares}}


def _calibration_target(A, dt, z0) -> dict:
    """F6 run 1, owner decision R1: the listed units' calibration targets (calibration.target_column) multiplied by
    `scale` and their calibrated values redone on the outcome emulator's calibration metric (model.cal_grid, as
    calibration.invert), every other unit held. Without a joint calibration the new value is the inversion at the
    scaled target. On the joint path the unit values come from the joint fit (offsets, group targets), which an
    inversion of one target would drop (Codex r1 P1-2 of the joint path): each listed unit's joint value moves by the
    difference between the inversions at the scaled and at the original target. Fail closed (not run): a listed unit
    not in the analysis, or, on the joint path, not in the joint calibration; a unit whose inversion is clamped at
    the range at either target (its move would be unknown); a test that moves no unit."""
    ct = dt.get("calibration_target") or {}
    us, sc = [str(u) for u in ct.get("units") or []], float(ct.get("scale", 1.0))
    cal = A.spec["calibration"]
    if cal.get("method") != "emulator_inversion" or not hasattr(A.model, "cal_grid"):
        return {"not_run": "a calibration_target test needs an emulator-inversion calibration and its emulator"}
    miss = [u for u in us if u not in A.ids]
    if miss:
        return {"not_run": f"listed units are not in the analysis: {miss[:5]}"}
    if A.joint is not None:
        miss = [u for u in us if u not in A.joint["z"]]
        if miss:
            return {"not_run": f"listed units are not in the joint calibration: {miss[:5]}"}
    lo, hi = (float(x) for x in cal["range"])
    from toolkit.analysis import calibration as C
    zgrid = np.linspace(lo, hi, C.GRID)
    pred = np.maximum.accumulate(A.model.cal_grid(us, A.theta0, zgrid), axis=1)
    tc = cal["target_column"]
    zs, units, clamped = dict(z0), {}, []
    for j, u in enumerate(us):
        y0 = float(A.model.by_id[u][tc])
        y1 = y0 * sc
        if not 0.0 < y1 < 1.0:
            return {"not_run": f"unit {u}'s scaled target {y1:g} is not inside (0, 1)"}
        t0, t1 = (math.log(y / (1.0 - y)) for y in (y0, y1))
        if not (pred[j, 0] <= min(t0, t1) and max(t0, t1) <= pred[j, -1]):
            clamped.append(u)
            continue
        i0, i1 = float(np.interp(t0, pred[j], zgrid)), float(np.interp(t1, pred[j], zgrid))
        new = float(z0[u]) + (i1 - i0) if A.joint is not None else i1
        if not lo <= new <= hi:
            clamped.append(u)
            continue
        zs[u] = new
        units[u] = {"target": y0, "target_scaled": y1, "z_before": float(z0[u]), "z": new,
                    "inversion": [i0, i1]}
    if clamped:
        return {"not_run": f"the emulator's calibration metric cannot reach the original or scaled target of "
                           f"{len(clamped)} listed unit(s) inside the calibration range (e.g. {clamped[:3]}), so their "
                           "moved values are unknown"}
    if not any(abs(v["z"] - v["z_before"]) > 1e-9 for v in units.values()):
        return {"not_run": "the scaled targets move no listed unit's calibrated value"}
    return {"z": zs, "scale": sc, "clamped": len(clamped),
            "record": {"scale": sc, "column": tc, "joint": A.joint is not None, "units": units}}


def run_one(A, dt, z0, ben0, cost0, plan, uq_data, out0=None) -> dict:
    t = dt["type"]
    thr = _threshold(A)
    sv = None                      # a parameter_value test on a spec-declared engine parameter value
    evs = {}                       # model corrections per tested value (Codex r2 P1-3)
    extra, rejected = {}, []
    if t == "interaction_rescale":
        r = _interaction(A, dt, ben0, cost0, plan, out0)
        if r.get("not_run"):
            return _not_run(A, dt, r["not_run"], r.get("info"))
        varied, cases, lowers, extra, rejected = r["varied"], r["cases"], r["lowers"], r["extra"], r["rejected"]
    elif t == "unit_attribute":
        ur = _unit_attribute(A, dt, z0, ben0, cost0, plan)
        if ur.get("not_run"):
            return _not_run(A, dt, ur["not_run"], ur.get("info"))
        varied, cases, lowers, extra, rejected, evs = (ur[k] for k in ("varied", "cases", "lowers", "extra", "rejected",
                                                                       "evs"))
        extra["_ua"] = ur["record"]
        arms = ur["arms"]          # each case's own analysis (arm_analysis): its solve, feasibility and reading
    elif t == "calibration_target":
        cr = _calibration_target(A, dt, z0)
        if cr.get("not_run"):
            return _not_run(A, dt, cr["not_run"])
        varied = (f"the calibration targets of the listed units multiplied by {cr['scale']:g}, their calibrated values "
                  "redone on the emulator (on the joint path, each moved by the change the target change implies)")
        _, ben, cost = A.evaluate(A.theta0, cr["z"])
        evs["case"] = list(A.last_events)
        extra["case"] = {"calibration_clamped_units": cr["clamped"]}
        extra["_ct"] = cr["record"]
        cases, lowers = [("case", ben, cost, None, None)], [False]
    elif t == "outcome_ratio":
        orr = _outcome_ratio(A, dt, out0, ben0, cost0, plan, z0)
        if orr.get("not_run"):
            return _not_run(A, dt, orr["not_run"])
        varied, cases, lowers = orr["varied"], orr["cases"], orr["lowers"]
        evs.update(orr.get("evs") or {})
        extra["_or"] = orr["record"]
        extra["_missing"] = list(orr["unpaired"])        # the packages with the component that have no counterpart
    elif t == "burden_scale":
        bsr = _burden_scale(A, dt, z0, out0, ben0, cost0)
        if bsr.get("not_run"):
            return _not_run(A, dt, bsr["not_run"])
        varied, cases, lowers, evs = bsr["varied"], bsr["cases"], bsr["lowers"], bsr["evs"]
        extra["_bs"] = bsr["record"]
    elif t == "boundary_engine":       # F6 run 4 R3 (RIG-002): the engine side of the boundary check, re-solved
        be = getattr(A, "boundary_engine", None)
        if not be or not be.get("ben"):
            return _not_run(A, dt, "the boundary check produced no engine tables (it runs on the emulator path, for "
                                   "units with a runner-up)")
        from toolkit.analysis.core import CostTable
        ben = {i: dict(ben0[i]) for i in A.ids}
        tot = {i: dict(cost0[i]) for i in A.ids}
        byc = {i: {k: dict(v) for k, v in (getattr(cost0, "by_component", {}).get(i) or {}).items()} for i in A.ids}
        for u, pair in be["pairs"].items():       # only the two compared cells (Codex review of #252 P1-1, P1-2)
            for k in pair:
                ben[u][k] = be["ben"][u][k]
                tot[u][k] = be["cost"][u][k]
                byc.setdefault(u, {})[k] = dict(be["cost_by"][u][k])
        cost = CostTable(tot, byc)
        pev = getattr(A, "point_events", None)       # #252 review P1-3; re-review: no record, not run
        if pev is None:
            return _not_run(A, dt, "the point evaluation's model corrections are not recorded (Analysis.point_events), "
                                   "so the re-solved plan could not be guarded")
        subst = {(u, k) for u, pair in be["pairs"].items() for k in pair}
        # re-review P1: a correction on a cell the engine now supplies no longer bears on it
        evs["engine_at_boundary"] = [e for e in pev if (str(e.get("unit")), e.get("package")) not in subst]
        varied = ("at the units of the boundary check, the benefits and costs of the packages run on the engine taken "
                  "from the engine instead of the emulator")
        cases, lowers = [("engine_at_boundary", ben, cost, None, None)], [False]
        extra["_be"] = {"units": sorted(be["ben"]), "pairs": {u: list(p) for u, p in be["pairs"].items()},
                        "run_packages": be["run"], "check": {u: dict(be["ben"][u]) for u in sorted(be["ben"])},
                        "benefit": {u: dict(ben[u]) for u in sorted(be["ben"])}}
    elif t == "scenario_excluded":
        return _not_run(A, dt, f"the spec holds the scenario value {dt['parameter']} fixed by name: {dt['reason']}",
                        {"parameter": dt["parameter"]})
    elif t in ("parameter_value", "prior_range", "fitted_range"):
        p = dt["parameter"]
        pl = plan_test(A.spec, dt, runtime_evidence(A))
        if pl["status"] != "runs":
            return _not_run(A, dt, pl["why"], {"rejected_values": pl["rejected"]} if pl["rejected"] else None)
        varied = (f"engine parameter {p} set to each end of its declared prior range ({dt.get('source')})"
                  if t == "prior_range" else
                  f"fitted engine parameter {p} set to each end of its {'jointly calibrated' if dt.get('joint') else 'fitted'}"
                  " range" if t == "fitted_range" else f"engine parameter {p} set to each tested value")
        from toolkit.spec import engine_parameters as PV
        comp = PV.companions(dt)       # owner, 20 Nov: companion engine parameters held in every case of the test
        if comp:
            varied += ", with " + ", ".join(f"{k} held at {v:g}" for k, v in sorted(comp.items())) + " in every case"
            extra["_with"] = dict(sorted(comp.items()))
        cases, lowers = [], []
        vals, rejected = [x["value"] for x in pl["perturbations"]], pl["rejected"]
        extra["_ident"] = [bool(x.get("identity")) for x in pl["perturbations"]]
        if t == "parameter_value" and p in PV.values(A.spec):   # the headline runs at the spec value: record the card
            # value it replaces
            cv = float(next(x.value for x in A.eng.parameters() if x.name == p))
            sv = {"value": PV.values(A.spec)[p], "card_value": cv,
                  "card_value_tested": any(abs(float(v) - cv) <= 1e-9 * max(1.0, abs(cv)) for v in vals)}
        # an emulator answer outside its design box is an extrapolation: plan_test() refused such values, with the box;
        # toolkit/analysis/batch.py widens the box to span the spec's own parameter_value test values
        for v in vals:
            theta = dict(A.theta0, **comp, **{p: float(v)})
            if A.method == "emulator_inversion":
                cz = A.calibrate(theta)
                zs = {i: x[0] for i, x in cz.items()}
                extra[v] = {"calibration_clamped_units": sum(bool(x[1]) for x in cz.values())}   # Codex r1 P1-3
            elif A.method == "posterior" and (p in (A.lik or {}).get("params", []) or p.startswith("z:")
                                              or p in (A.lik or {}).get("nuisance", [])):
                from toolkit.analysis import calibration as C
                if p.startswith("z:"):     # a unit attribute at each end of its range, the calibration redone
                    fit = C.fit_posterior_panel(A.spec, A.model, fixed_z={p[2:]: float(v)}, sample_it=False)
                    zs = dict(fit["z"], **{p[2:]: float(v)})
                else:                      # an engine parameter, or a source's bias parameter (never an engine input)
                    fit = C.fit_posterior_panel(A.spec, A.model, fixed_params={p: float(v)}, sample_it=False)
                    zs = dict(fit["z"])
                zs = {i: zs.get(i, fit["fixed_z"].get(i)) for i in A.ids}
                theta = dict({k: x for k, x in A.theta0.items() if k != p or k in fit["theta"]}, **fit["theta"])
            else:
                zs = z0
            _, ben, cost = A.evaluate(theta, zs)
            evs[v] = list(A.last_events)
            same_cost = all(abs(cost[i][k] - cost0[i][k]) <= 1e-9 * max(1.0, abs(cost0[i][k])) for i in A.ids for k in A.pk)
            lowers.append(same_cost and _lowers_only_unchosen(ben0, ben, plan))
            cases.append((v, ben, cost, None, None))
    elif t == "anchor_range":
        varied = (f"the external estimates of anchors {', '.join(dt['anchors'])} set together to the 2.5% and 97.5% "
                  "ends of their published intervals")
        cases, lowers = [], []
        for v in dt["values"]:
            _, ben, cost = A.evaluate(A.theta0, z0, sampled=dt["ends"][v])
            evs[v] = list(A.last_events)
            cases.append((v, ben, cost, None, None))
            lowers.append(False)
    elif t == "group_rule":
        from toolkit.analysis import variants as V
        a = copy.deepcopy(V.base_alloc(A))        # the signed rules; a headline variant's rule is joined below
        rules = dict(a.get("group_rules") or {})
        if dt.get("add"):
            add = dict(dt["add"])
            rules[add.pop("id", dt["id"])] = add
            varied = f"group rule added on {add.get('by')} for {', '.join(map(str, add.get('components') or []))}"
        else:
            rules.pop(dt["rule"], None)
            varied = f"group rule {dt['rule']} removed"
        a["group_rules"] = rules
        if not rules:
            a.pop("group_rules")
        feas = V.carry(A, a)      # F6 S1-6: a headline variant's rule, which the test can neither replace nor remove
        cases = [("with" if dt.get("add") else "without", ben0, cost0, None, feas)]
        lowers = [False]
    elif t == "envelope":
        varied = "the envelope set to each tested value"
        fixed = sum(float(v) for v in (A.spec["constraints"].get("fixed_costs_usd") or {}).values())
        A.spec.packages()
        bound = getattr(A.spec, "prune_budget", None)
        if bound is not None and any(float(v) - fixed > bound * (1 + 1e-12) for v in dt["values"]):
            return _not_run(A, dt, "an envelope above the declared one, and the packages were generated within the "
                                   "declared envelope (options.packages.within_envelope): drop within_envelope to "
                                   "test larger envelopes")
        # F6 S1-1b: the reserve policy holds at each envelope (the same fraction held back), so the declared envelope
        # reproduces the headline plan
        cases = [(v, ben0, cost0, A.planned(float(v) - fixed), None) for v in dt["values"]]
        lowers = [False] * len(cases)
    elif t == "cost_items":
        mult = {k: float(m) for k, m in dt["multipliers"].items()}      # the ids as the cost items declare them
        varied = "the unit costs of the listed cost items multiplied together (cost_multipliers)"
        _, ben, cost = A.evaluate(A.theta0, z0, cost_mult=mult)
        evs["case"] = list(A.last_events)
        extra["case"] = {"cost_multipliers": mult}
        cases, lowers = [("case", ben, cost, None, None)], [False]
    else:
        raise ValueError(f"decision test {dt.get('id')}: unknown type {t}")
    results = []
    A_ = A
    for n_, ((v, ben, cost, budget, feas), low) in enumerate(zip(cases, lowers)):
        A = arms[n_] if t == "unit_attribute" else A_
        try:
            sol = A.solve(ben, cost, budget=budget, feas=feas)
        except RuntimeError as e:
            if t == "boundary_engine" and str(e).strip() == "optimizer status infeasible":     # #252 review P2-5
                return _not_run(A, dt, "with the engine's costs at the boundary units no allocation that meets the "
                                       "constraints fits the budget the plan is solved within (the solver proves it infeasible)")
            if t != "cost_items" or str(e).strip() != "optimizer status infeasible":
                raise
            # Codex r1: the price case has no affordable plan; the record keeps the prices and says why
            return _not_run(A, dt, "at these prices no allocation that meets the constraints fits the budget the plan "
                                   "is solved within (the solver proves it), so there is no re-solved plan to compare "
                                   "with the point plan", {"cost_multipliers": dict(mult)})
        ch = sol["choice"]
        A.guard(f"decision test {dt['id']} at {v}", [plan, ch], events=evs.get(v, []))
        # F6 S1-5: what moves beside the share (regret, population, dollars by component, units by group)
        # (the point plan judged under the test's costs, feasibility and planning budget: Codex r1 P2-1)
        bchg = {c: max((abs(float(ben[i][k]) - float(ben0[i][k])) for i in A.ids for k in A.pk if c in A.pk[k]),
                       default=0.0) for c in (A.spec["options"].get("components") or {})}
        results.append({"value": v, **MV.summarise(A, plan, ch, ben, cost, sol["objective"], budget=budget, feas=feas),
                        "benefit_change": bchg,
                        "objective": sol["objective"], "recommendation": A.mix_text(ch),
                        "provably_unchanged": bool(low), **(extra.get(v) or {})})
    A = A_
    worst = max(results, key=lambda r: r["share_units_changed"])
    th = MV.thresholds(A.spec["analysis"])
    agg = MV.aggregate(results)       # each criterion's worst value, with its own breakdown (Codex r1 P2-3)
    comps = set(dt.get("components") or [])
    in_draws = sorted(comps & set(uq_data.get("components_in_any_draw_plan") or [])) if comps else None
    in_plan = sum(bool(A.pk[plan[i]] & comps) for i in A.ids) if comps else None
    if all(r["provably_unchanged"] for r in results):
        stmt = ("This test cannot move the plan: it only lowers the benefit of packages that no unit receives in the "
                "point plan, so the point plan stays optimal")
        if comps:
            stmt += (f"; {', '.join(sorted(comps))} is in {'some' if in_plan else 'no'} unit of the point plan and in "
                     f"{'some' if in_draws else 'none'} of the re-optimised uncertainty draws")
        can_move = False
    else:
        stmt = "This test can move the plan: it was re-solved for each value"
        can_move = True
    if sv:
        stmt += (f"; the headline uses the spec value of {dt['parameter']} (engine_parameters), and the engine card "
                 "value " + ("is one of the tested values" if sv["card_value_tested"]
                             else "is not among the tested values"))
    if rejected:
        stmt += "; some requested values could not be reached and were rejected"
    if any(r.get("calibration_clamped_units") for r in results):
        stmt += ("; at some tested values the calibration clamped at its range for some units, so those units do not "
                 "match their targets there (calibration_clamped_units per value)")
    finding = dt.get("finding") or f"decision_test:{dt['id']}"
    rec = {"statement": stmt + ".", "status": "run", "can_move_plan": can_move, "finding": finding,
           "test_id": dt["id"], "type": t, "question": dt.get("text", ""), "varied": varied,
           "criterion": (f"the package changes in more than {thr:.0%} of units, or keeping the point plan loses more "
                         f"than {th['regret']:.1%} of the re-optimised objective, or more than {th['dollars']:.0%} of "
                         "the allocatable budget is reallocated across units and components, or the point plan is "
                         "not feasible under the test"),
           **agg, "share_threshold": thr, "regret_threshold": th["regret"], "dollars_threshold": th["dollars"],
           "recommendation": {"with": A.mix_text(plan), "without": worst["recommendation"]},
           "results": results, "rejected_values": rejected, "produced_by": "harness", "producer": PRODUCER,
           # #215 round 4: the realised change in each component's benefit, and the packages a test had to skip
           "benefit_change": {c: max(float(r["benefit_change"].get(c, 0.0)) for r in results)
                              for c in (A.spec["options"].get("components") or {})},
           "missing_subtraction": list(extra.get("_missing") or []),
           "perturbation_identity": list(extra.get("_ident") or []),
           **({"with": dict(extra["_with"])} if extra.get("_with") else {}),     # companions held in every case
           "benefit_change_by_package": {k: max(max((abs(float(c_[1][i][k]) - float(ben0[i][k])) for i in A.ids),
                                                    default=0.0) for c_ in cases) for k in A.pk},
           "package_components": {k: sorted(v) for k, v in A.pk.items()}}
    if sv:
        rec["spec_value"] = sv
    if t == "cost_items":
        rec["cost_multipliers"] = dict(extra["case"]["cost_multipliers"])
    if t == "unit_attribute":       # the column, the units changed and each modified table's sha256
        rec["unit_attribute"] = extra["_ua"]
    if t == "calibration_target":   # each listed unit's target and calibrated value, before and after
        rec["calibration_target"] = extra["_ct"]
    if t == "outcome_ratio":        # the package pairs and one unit's recomputed benefit (a check)
        rec["outcome_ratio"] = extra["_or"]
    if t == "boundary_engine":      # the boundary units, the packages run on the engine there, their benefits
        rec["boundary_engine"] = extra["_be"]
    if t == "burden_scale":         # each reference's group, model and external values, factor; one unit per group
        rec["burden_scale"] = extra["_bs"]
    if comps:
        rec["relevance"] = {"components": sorted(comps), "units_with_component_point_plan": in_plan,
                            "components_in_any_draw_plan": in_draws}
    if t == "interaction_rescale":
        rec["engine_arm_or"], rec["engine_interaction"] = extra.get("_arm"), extra.get("_int")
        rec["arm_source"] = extra.get("_src")
        if extra.get("_inputs"):
            rec["arm_inputs"] = extra["_inputs"]
    return rec


def _rescale(ratio: float, g: float) -> float:
    """The one transformation of the test (Codex r2 P1-5): an increment, as a ratio with and without the component, is
    rescaled on the log scale (ratio ** g). It is applied to the benchmark's odds ratio (a11 / a10) to solve and verify
    the target interaction, and to each unit's outcome ratio (package / package without the component) to change the
    allocation, so the two cannot disagree on the scale."""
    return ratio ** g


def _interaction(A, dt, ben0, cost0, plan_, out0) -> dict:
    pl = plan_test(A.spec, dt, runtime_evidence(A))
    if pl["status"] != "runs":
        return {"not_run": pl["why"], "info": pl.get("info")}
    info = pl["info"]
    arm, eng_int = info["engine_arm_or"], info["engine_interaction"]
    comp = set(dt["components"])
    cases, lowers, rejected = [], [], pl["rejected"]
    extra = {"_arm": arm, "_int": eng_int, "_src": f"verified benchmark results ({dt.get('benchmark')}), {info['src']}",
             "_inputs": info["inputs"], "_missing": list(info.get("missing_subtraction") or []),
             "_ident": [bool(x.get("identity")) for x in pl["perturbations"]]}
    o = A.primary
    for pt in pl["perturbations"]:
        v, g = pt["value"], pt["scale"]
        if abs(pt["achieved"] - v) > ACHIEVED_RTOL * abs(v):
            raise RuntimeError(f"decision test {dt['id']}: achieved interaction {pt['achieved']} != requested {v}")
        ben = {}
        for i in A.ids:
            ben[i] = {}
            y0 = out0[i]["y"][A.comp][o]
            for k in A.pk:
                base = pt["packages"].get(k)
                if base is not None:
                    yb, yk = out0[i]["y"][base][o], out0[i]["y"][k][o]
                    if yb <= 0 or yk <= 0:
                        ben[i][k] = ben0[i][k]      # nothing to rescale (no outcome left)
                        continue
                    yk_new = yb * _rescale(yk / yb, g)
                    ben[i][k] = A.dfac * (y0 - yk_new)
                else:
                    ben[i][k] = ben0[i][k]
        cases.append((v, ben, None, None, None))
        lowers.append(_lowers_only_unchosen(ben0, ben, plan_))
        extra[v] = {"increment_scale": g, "achieved_interaction": pt["achieved"]}
    with_any = set(dt["with_any"])
    cases = [(v, ben, cost0, b_, f_) for (v, ben, _c, b_, f_) in cases]
    varied = (f"the increment of {sorted(comp)} given any of {sorted(with_any)} rescaled on the log scale so the "
              f"engine's interaction odds ratio in the {dt.get('benchmark')} setting equals each tested value")
    return {"varied": varied, "cases": cases, "lowers": lowers, "extra": extra, "rejected": rejected}

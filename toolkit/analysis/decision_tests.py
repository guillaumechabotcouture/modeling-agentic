def _table_sha(rows) -> str:
    """sha256 of a units table as CSV (its own column order, '\\n' line ends): the modified table's identity."""
    import csv
    import hashlib
    import io
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=list(rows[0]) if rows else [], lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    return hashlib.sha256(buf.getvalue().encode()).hexdigest()


def _num_or_none(x):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return None
    return v if math.isfinite(v) and not isinstance(x, bool) else None


def unit_attribute_cases(spec, dt) -> dict:
    """What a unit_attribute test changes, read from the spec and the units table alone (no engine): {why} when it
    cannot, else {column, attributes, units, chosen, mode, cases: [(label, {unit: new value})], inputs, ids, base,
    old}. A set_from table is read once here; `inputs` holds the sha256 of exactly the bytes parsed."""
    ua = dt.get("unit_attribute")
    if not isinstance(ua, dict) or not ua.get("column"):
        return {"why": "give unit_attribute: {column, units: [ids] | all, values: [..] | scale: [..] | set_from: <table>}"}
    col = str(ua["column"])
    base = spec.units()
    if not base or col not in base[0]:
        return {"why": f"{col!r} is not a column of the units table"}
    attrs = []
    for a, m in ((spec.raw.get("decision_units") or {}).get("engine_attributes") or {}).items():
        if not isinstance(m, dict):
            continue
        cs = [m["column"]] if "column" in m else list((m.get("columns") or {}).values()) \
            if isinstance(m.get("columns"), dict) else list(m.get("columns") or [])
        if col in cs:
            if "split" in m:
                return {"why": f"column {col} holds a list (split) for attribute {a}; a test varies a numeric column"}
            attrs.append(a)
    if not attrs:
        return {"why": f"column {col} feeds no engine unit attribute (decision_units.engine_attributes binds none to "
                       "it), so changing it cannot reach the engine"}
    cal = spec.raw.get("calibration") or {}
    if cal.get("method") not in (None, "none") and cal.get("attribute") in attrs:
        return {"why": f"column {col} feeds {cal['attribute']}, which the calibration sets per unit, so the engine "
                       "never reads the column"}
    uid = spec.uid
    ids = [str(u[uid]) for u in base]
    sel = ua.get("units", "all")
    if sel == "all":
        chosen = list(ids)
    elif isinstance(sel, list) and sel:
        unknown = [str(x) for x in sel if str(x) not in ids]
        if unknown:
            return {"why": f"units {unknown} are not in the units table"}
        chosen = [str(x) for x in sel]
    else:
        return {"why": "units: `all` or a non-empty list of unit ids"}
    modes = [k for k in ("values", "scale", "set_from") if k in ua]
    if len(modes) != 1:
        return {"why": f"give exactly one of values, scale or set_from (got {modes or 'none'})"}
    mode = modes[0]
    old = {i: _num_or_none(u[col]) for i, u in zip(ids, base)}
    if any(old[i] is None for i in chosen):
        return {"why": f"column {col} is not a finite number in every selected unit"}
    cases, inputs = [], {}
    if mode in ("values", "scale"):
        xs = ua[mode]
        if not isinstance(xs, list) or not xs or any(_num_or_none(x) is None for x in xs):
            return {"why": f"{mode}: a non-empty list of numbers"}
        for x in xs:
            cases.append((float(x), {i: float(x) if mode == "values" else old[i] * float(x) for i in chosen}))
    else:
        import csv
        import hashlib
        import io
        rel = str(ua["set_from"])
        root = os.path.realpath(spec.base)
        p = os.path.realpath(spec.resolve(rel))
        if os.path.isabs(rel) or os.path.commonpath([root, p]) != root:
            return {"why": f"set_from {rel} must be a table inside the run directory (a relative path)"}
        try:
            with open(p, "rb") as f:
                raw = f.read()               # one read: the bytes parsed are the bytes hashed (#228 r1 P2-6)
            rows = list(csv.DictReader(io.StringIO(raw.decode("utf-8"), newline="")))
        except (OSError, UnicodeDecodeError) as e:
            return {"why": f"set_from {rel} cannot be read ({type(e).__name__})"}
        inputs[rel] = hashlib.sha256(raw).hexdigest()
        if not rows or uid not in rows[0] or col not in rows[0]:
            return {"why": f"set_from {rel}: give columns {uid} and {col}"}
        new = {str(r[uid]): _num_or_none(r[col]) for r in rows}
        unknown = [i for i in new if i not in ids]
        if unknown or any(v is None for v in new.values()):
            return {"why": f"set_from {rel}: units {unknown} are not in the units table" if unknown else
                    f"set_from {rel}: {col} is not a finite number in every row"}
        if sel != "all":
            new = {i: v for i, v in new.items() if i in chosen}
        cases.append((rel, new))
    import re
    integer_column = all(re.fullmatch(r"\s*[+-]?\d+\s*", str(u[col])) for u in base)
    return {"column": col, "attributes": sorted(attrs), "units": sel if sel == "all" else chosen, "mode": mode,
            "cases": cases, "inputs": inputs, "ids": ids, "base": base, "old": old, "integer_column": integer_column}


def _cell(c, v) -> str:
    """A tested value in its column's own format (#228 re-review P2-1): in a column whose every cell is an integer
    literal (a binary eligibility flag, a count) an integral value stays an integer literal, which the eligibility
    and units readers accept; any other value is written as a float literal."""
    v = float(v)
    return str(int(v)) if c.get("integer_column") and v.is_integer() else repr(v)


def _arm_rows(c, new) -> list[dict]:
    return [dict(u, **{c["column"]: _cell(c, new[i])}) if i in new else dict(u) for i, u in zip(c["ids"], c["base"])]


class _UnitOutcome(dict):
    """Every per_outcome cost driver at 1: the cost a units table implies for a package apart from the model's
    outcomes (those reach the plan through the built inputs and populations, compared on their own)."""

    def get(self, k, d=None):
        return 1.0

    def __missing__(self, k):
        return 1.0


def arm_reads(spec, rows, kind=None) -> tuple[dict, dict]:
    """Everything an arm's analysis reads from a units table (#228 re-review P2-2), as (per unit, whole table): per
    unit the built model inputs (encoded emulator features on the emulator path, engine attributes otherwise), the
    population of every group the model and the costs read, the calibration target and region cells, the cost of
    every package (per_outcome drivers at 1), the feasible packages, the lock and the cap weights; for the table
    each cap's maximum and the group links. Raises ValueError when the alloc readers reject the table."""
    import copy as _copy
    from toolkit.alloc import costs as acosts, packages as apackages
    from toolkit.analysis import features as FT
    spec.packages()       # the headline's package set (pruned over every arm's table), never one pruned over `rows`
    sp = _copy.copy(spec)
    sp._units = rows
    sp._pruned = getattr(spec, "_pruned", None)
    alloc = sp.alloc_spec()
    fe = apackages.feasibility(alloc, rows)
    cm = acosts.cost_matrix(alloc, rows, outcome=lambda u, p: _UnitOutcome())
    cols = sorted({str(m["column"]) for m in (sp["decision_units"].get("populations") or {}).values()}
                  | {str(x) for x in (sp["options"].get("populations") or {}).values()}
                  | {str(x) for x in (sp["calibration"].get("target_column"), sp["decision_units"].get("region"))
                     if x})
    built = (lambda r: FT.vector(sp, r)) if kind == "emulator" else sp.unit_attributes    # noqa: E731
    per = {}
    for u in rows:
        i = str(u[sp.uid])
        per[i] = {"inputs": built(u), "cells": {k: u.get(k) for k in cols},
                  "cost": {p: x["total"] for p, x in cm[i].items()}, "feasible": fe["feasible"][i],
                  "lock": fe["locks"].get(i), "cap_weights": {c_["name"]: c_["weights"][i] for c_ in fe["caps"]}}
    table = {"caps": {c_["name"]: c_["max"] for c_ in fe["caps"]},
             "links": [(x["name"], x["groups"], x["class"]) for x in fe.get("links") or []]}
    return per, table


def constraints_of(A) -> tuple:
    """What an analysis lets a plan choose (#228 re-review P2-3): the feasible packages and locks per unit, the caps
    (maximum and weights), the group links and the planning budget."""
    f = A.feas
    return (f["feasible"], f.get("locks"), [(c["name"], c["max"], c["weights"]) for c in f.get("caps") or []],
            [(x["name"], x["groups"], x["class"]) for x in f.get("links") or []], A.budget, A.plan_budget)


def arm_tables(spec) -> list[list[dict]]:
    """Every units table a unit_attribute test of the spec evaluates (Spec.packages prunes over these too, so the
    headline and every arm share one package set)."""
    out = []
    for dt in (spec.raw.get("analysis") or {}).get("decision_tests") or []:
        if isinstance(dt, dict) and dt.get("type") == "unit_attribute":
            c = unit_attribute_cases(spec, dt)
            out += [] if "why" in c else [_arm_rows(c, new) for _lbl, new in c["cases"]]
    return out


def design_features_box(spec):
    """Each emulator feature's range over the units the design copies (toolkit/analysis/batch.py design: design points
    are real units), the box sign-off and the pre-run plan check against; None when the features cannot be read.
    The run checks again against the fitted emulator's own domain (runtime_evidence)."""
    from toolkit.analysis import features as FT
    try:
        names = [FT.name(f) for f in FT.declared(spec.raw)]
        vs = [FT.vector(spec, u) for u in spec.units()]
    except (ValueError, TypeError, KeyError, OSError):
        return None
    return {nm: (min(v[j] for v in vs), max(v[j] for v in vs)) for j, nm in enumerate(names)} if vs else {}


def plan_unit_attribute(spec, dt, card, kind=None, features_box=None) -> dict:
    """The cases a unit_attribute test runs, without running the engine: each a copy of the units table as
    Spec.units() reads it, with column `column` set (values), multiplied (scale) or taken per unit from a table in the
    run directory (set_from) for the listed units (default all). Refused (status not_run, why): what
    unit_attribute_cases refuses (unknown column, a column feeding no engine attribute or only the calibrated one,
    unknown units, value modes, set_from); no declared domain (EngineCard.valid_ranges of the attribute) or a case
    outside it; on the emulator path a column that reaches no emulator feature or a case outside the design box of a
    feature; a case whose table the units readers reject (rejected, with their reason); a test whose every case
    leaves everything the arm's analysis reads unchanged (arm_reads: engine attributes or encoded emulator features,
    populations, costs, feasibility and caps). A changed cell keeps its column's format (_cell). With the emulator box unknown (None) the plan says so and the run
    refuses a case outside the fitted emulator's domain."""
    def no(why, rejected=()):
        return {"status": "not_run", "why": why, "perturbations": [], "rejected": list(rejected)}
    c = unit_attribute_cases(spec, dt)
    if "why" in c:
        return no(c["why"])
    col, attrs = c["column"], c["attributes"]
    doms = {a: (card.valid_ranges or {}).get(a) for a in attrs}
    if any(not (isinstance(d, (list, tuple)) and len(d) == 2) for d in doms.values()):
        return no(f"the engine card declares no valid range for {sorted(a for a, d in doms.items() if not d)} "
                  "(EngineCard.valid_ranges), so the column has no declared domain to check the tested values against")
    lo, hi = max(float(d[0]) for d in doms.values()), min(float(d[1]) for d in doms.values())
    from toolkit.analysis import features as FT
    feats = []
    if kind == "emulator":
        feats = [FT.name(f) for f in FT.declared(spec.raw)
                 if f == col or (isinstance(f, dict) and f.get("attribute") in attrs)]
        if not feats:
            return no(f"column {col} is not an emulator input (analysis.emulator.features names neither it nor "
                      f"{attrs}), so the emulator's answer cannot respond to it; declare a feature or use direct "
                      "evaluation")
    names = [FT.name(f) for f in FT.declared(spec.raw)]
    try:
        per0, tab0 = arm_reads(spec, c["base"], kind)
    except (ValueError, TypeError, KeyError) as e:
        return no(f"the inputs of the units table cannot be built ({e})")
    tol = 1e-9 * max(hi - lo, 1.0)
    perts, rejected = [], []
    for label, new in c["cases"]:
        out_ = sorted(i for i, v in new.items() if not lo - tol <= v <= hi + tol)
        if out_:
            rejected.append({"value": label, "units_outside": out_, "declared_domain": [lo, hi]})
            continue
        rows = _arm_rows(c, new)
        by = dict(zip(c["ids"], rows))
        try:     # #228 r1 P2-4 and re-review P2-2: a unit changes when anything the arm's analysis reads for it
            # changes (built inputs, populations, costs, feasibility, caps), not when a cell does
            per, tab = arm_reads(spec, rows, kind)
        except (ValueError, TypeError, KeyError) as e:     # re-review P2-1: refused, never a crash in the run
            rejected.append({"value": label, "units_table_rejected": str(e)})
            continue
        try:
            changed = [i for i in c["ids"] if per[i] != per0[i]]
            far = sorted({i for i in changed for nm, v in zip(names, FT.vector(spec, by[i])) if nm in feats
                          and features_box and nm in features_box
                          and not features_box[nm][0] - tol <= v <= features_box[nm][1] + tol})
        except (ValueError, TypeError, KeyError) as e:
            return no(f"the inputs of a modified unit cannot be built ({e})")
        if far:
            rejected.append({"value": label, "units_outside": far,
                             "design_box": {nm: list(features_box[nm]) for nm in feats if nm in features_box}})
            continue
        perts.append({"value": label, "units_changed": changed, "table_sha256": _table_sha(rows),
                      "identity": not changed and tab == tab0, "_rows": rows})
    if not perts:
        return no(f"every case puts some unit outside the column's declared domain [{lo:g}, {hi:g}] or the emulator's "
                  "design box, or gives a units table the units readers reject (the rejected cases say which)",
                  rejected)
    if all(x["identity"] for x in perts):
        return no("every case leaves everything the analysis reads from the units table unchanged (built inputs, "
                  "populations, costs, feasibility and caps: an identity): the test varies nothing", rejected)
    info = {k: c[k] for k in ("column", "attributes", "mode", "units", "inputs")}
    info.update(declared_domain=[lo, hi], base_table_sha256=_table_sha([dict(u) for u in c["base"]]),
                emulator_features=feats)
    if kind == "emulator":
        info["design_box"] = ("checked" if features_box is not None else
                              "unknown before the run: the run refuses a case outside the fitted emulator's domain")
    return {"status": "runs", "why": "", "perturbations": perts, "rejected": rejected, "info": info}


def arm_analysis(A, rows):
    """A separate analysis for one arm, built from the modified units table by the constructors the run uses for the
    headline (#228 r1 P1-1..P2-3): a Spec reading `rows`, its alloc spec, caps and feasibility (Analysis), the headline
    variant (variants.apply_headline), the model's per-unit state (a DirectModel built anew; an emulator copied with its
    rows and features rebuilt by features.vector, its fit unchanged), and the headline's calibration, joint region,
    anchor and reserve. The package set is the headline's: Spec.packages prunes over every arm's table too. The arm is
    discarded after use; the headline analysis is never modified."""
    import copy as _copy
    from toolkit.analysis import features as FT
    from toolkit.analysis import variants as V
    from toolkit.analysis.core import Analysis
    from toolkit.analysis.model import DirectModel
    sp = _copy.copy(A.spec)
    sp._units = rows
    sp._pruned = getattr(A.spec, "_pruned", None)
    if A.model.kind == "direct":
        m = DirectModel(sp, log=A.log)
    else:
        m = _copy.copy(A.model)
        m.spec, m.by_id = sp, {str(u[sp.uid]): u for u in rows}
        m.fv = {i: FT.vector(sp, u) for i, u in m.by_id.items()}
    A2 = Analysis(sp, m, log=A.log)
    A2.joint, A2.lik, A2.flagged, A2.anchor = A.joint, A.lik, A.flagged, A.anchor
    A2.theta0 = dict(A.theta0)
    V.apply_headline(A2)
    A2.set_reserve(A.reserve_fraction)
    return A2


def artifact_inputs(recs, run_dir) -> list:
    """(path, sha256) of each set_from table as the test read it, for Store.write (the bytes executed are the bytes
    bound; never re-read at publication)."""
    return sorted({(os.path.join(run_dir, f), h) for x in recs
                   for f, h in ((x.get("unit_attribute") or {}).get("inputs") or {}).items()})


def _unit_attribute(A, dt, z0, ben0, cost0, plan) -> dict:
    pl = plan_test(A.spec, dt, runtime_evidence(A))
    if pl["status"] != "runs":
        return {"not_run": pl["why"], "info": {"rejected_values": pl["rejected"]} if pl["rejected"] else None}
    info = pl["info"]
    recal = A.method == "emulator_inversion" and A.joint is None
    cases, lowers, extra, evs, arms = [], [], {"_ident": [bool(x["identity"]) for x in pl["perturbations"]]}, {}, []
    for pt in pl["perturbations"]:
        v = pt["value"]
        A2 = arm_analysis(A, pt["_rows"])
        zs = z0
        if recal:       # the calibration redone on the modified table, as a parameter_value test redoes it
            cz = A2.calibrate(A2.theta0)
            zs = {i: x[0] for i, x in cz.items()}
            extra[v] = {"calibration_clamped_units": sum(bool(x[1]) for x in cz.values())}
        _, ben, cost = A2.evaluate(A2.theta0, zs)
        evs[v] = list(A2.last_events)
        same_cost = all(abs(cost[i][k] - cost0[i][k]) <= 1e-9 * max(1.0, abs(cost0[i][k])) for i in A.ids for k in A.pk)
        # re-review P2-3: the point plan stays optimal only if the arm also leaves every alternative and constraint
        same_feas = constraints_of(A2) == constraints_of(A)
        lowers.append(same_cost and same_feas and _lowers_only_unchosen(ben0, ben, plan))
        cases.append((v, ben, cost, None, None))
        arms.append(A2)
    how = {"values": "set to each tested value", "scale": "multiplied by each tested factor",
           "set_from": "set per unit from the table named"}[info["mode"]]
    varied = (f"units-table column {info['column']} (engine unit attribute {', '.join(info['attributes'])}) {how} in "
              f"{'every unit' if info['units'] == 'all' else 'the listed units'}; the calibration "
              + ("redone on the modified table" if recal else "held at the headline values"))
    rec = dict(info, calibration="redone" if recal else "held", cases=[
        {k: x[k] for k in ("value", "units_changed", "table_sha256", "identity")} for x in pl["perturbations"]],
        rejected=pl["rejected"])
    return {"varied": varied, "cases": cases, "lowers": lowers, "extra": extra, "rejected": pl["rejected"],
            "evs": evs, "record": rec, "arms": arms}



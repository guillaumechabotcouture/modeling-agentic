"""Decision tests (spike lesson 8): does the plan change when a quantity is varied?

Types (spec `analysis.decision_tests`):
  interaction_rescale  the spike's DT1: the increment of `components` on top of any of `with_any`
                       is rescaled so the engine's interaction odds ratio in the benchmark setting
                       equals each value. The arm odds ratios come only from the engine's verified
                       benchmark results (toolkit/engines/benchmark.py verified_benchmarks: written by
                       the runner for this engine's current code), never from the spec (Codex P1-13).
                       A value the rescaling cannot reach (scale outside [0, MAX_SCALE]) is rejected,
                       and every reached value is checked: the achieved interaction equals the
                       requested one (Codex P1-12);
  parameter_value      an engine parameter set to each value (an emulator input on the emulator path). For a
                       parameter whose value the signed spec sets (engine_parameters), the point plan is the
                       headline at the spec value, and the result records the card value (`spec_value`);
  group_rule           a constraints.group_rules rule removed (or `add:` a rule) and the plan re-solved;
  envelope             the plan re-solved at each envelope;
  cost_items           one price case: the unit costs of the listed cost items multiplied together
                       (`multipliers: {cost_item_id: m}`) and the plan re-solved. The benefits do not change. It
                       is for prices that move together (one price list for several products), which the
                       one-at-a-time cost sensitivity cannot show;
  unit_attribute       (F6) a units-table column that feeds an engine unit attribute, changed for the listed units
                       (`unit_attribute: {column, units: [ids] | all, values | scale | set_from}`): each case is a
                       copy of the table Spec.units() read, put in place for that case only (units_table), with the
                       calibration redone on the emulator-inversion path and held otherwise. Refused when the column,
                       a unit or the domain (the attribute's EngineCard.valid_ranges) is wrong, or every case is an
                       identity (plan_unit_attribute); the record names the column, units changed and table sha256;
  prior_range          (automatic, v2d note §2.4) one per prior-dominated parameter the draws vary
                       (toolkit/spec/priors.py): the parameter at each end of its declared range, the
                       calibration redone, the plan re-solved. Generated by the harness, id
                       `prior_range_<parameter>`; the spec cannot declare or remove one.
A test with at least one usable value writes `models/decision_tests/<id>.yaml` in the Phase 49
result schema (finding, varied, criterion, decision_changes, recommendation.with / without,
share_units_changed, share_threshold) with `produced_by: harness`. Beside the share, each value and the test
report what moves (F6 S1-5, toolkit/analysis/moves.py): regret, population whose package changes, dollars moved
by component and units changing by group; the plan changes on the share, the regret share or the dollars-moved
share, each against its threshold, and `triggered_by` names which. A test with none writes no
result file (a declaration citing it is then invalid) and is reported as not run, with why.

Relevance, up front: when a test changes only benefits, and every benefit it changes goes down and
belongs to a package no unit receives in the point plan, the point plan stays optimal (its value is
unchanged and no alternative improves). The file then says first that the test cannot move the plan.
Statements are words only; every number in results.md comes from computed claims (Codex P1-4).
"""

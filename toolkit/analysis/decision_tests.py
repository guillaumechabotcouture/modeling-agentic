def _lowers_only_unchosen(ben0, ben, plan) -> bool:
    for i in ben0:
        for k, v in ben0[i].items():
            if ben[i][k] != v and (ben[i][k] > v or plan[i] == k):
                return False
    return True


def run_all(A, z0, out0, ben0, cost0, plan, uq_data, run_dir) -> list[dict]:
    os.makedirs(os.path.join(run_dir, DIR), exist_ok=True)
    out = []
    dts = list(A.spec["analysis"].get("decision_tests") or []) + prior_range_tests(A)
    ids = [str(dt.get("id")) for dt in dts]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if dup:     # F6 S2-5d review r3: declared and automatic tests share one result path per id
        raise ValueError(f"decision tests: ids {dup} are used twice (a declared test shadows an automatic one); "
                         "rename the declared test")
    for dt in dts:
        rec = run_one(A, dt, z0, ben0, cost0, plan, uq_data, out0)
        if dt.get("automatic"):
            rec["automatic"] = True
        p = os.path.join(run_dir, DIR, f"{dt['id']}.yaml")
        rel = f"{DIR}/{dt['id']}.yaml".replace(os.sep, "/")
        from toolkit.analysis.artifacts import _safe_io
        if rec.get("status") == "not_run":
            _safe_io().remove_nofollow(run_dir, rel)      # no stale result file from an earlier run
            rec["path"] = None
        else:
            _safe_io().write_nofollow(run_dir, rel, yaml.safe_dump(plain(rec), sort_keys=False, width=120).encode(),
                                      atomic=True)
            rec["path"] = os.path.relpath(p, run_dir)
        out.append(rec)
    return out


def departure_verdicts(departures, targets, records) -> list[dict]:
    """#215: each departure's verdict from what its decision test recorded (records: test id -> the harness's
    decision-test record, whose file the manifest hashes). Effective only when the test ran, at least one of its
    perturbations was not an identity at the calibrated point, it skipped no targeted package for want of a
    subtraction package, and it changed the benefit of a targeted package: one holding the departed benchmark's own
    pair (an interaction), or a departed component. The run's contract recomputes this from the records."""
    out = []
    for d in departures:
        key, tid = d.get("benchmark") or d.get("component"), str(d.get("decision_test"))
        tgt = targets.get(key) or {}
        rec = records.get(tid)
        pkc = {k: set(v) for k, v in ((rec or {}).get("package_components") or {}).items()}
        pair = [set(v) for v in (tgt.get("pair") or {}).values()]
        if tgt.get("estimand") == "interaction" and len(pair) == 2:
            target = {k for k, cs in pkc.items() if all(side & cs for side in pair)}
            what = f"a package holding the benchmark's pair ({[sorted(x) for x in pair]})"
        else:
            comps = set(tgt.get("components") or [])
            target = {k for k, cs in pkc.items() if cs & comps}
            what = f"a package holding {sorted(comps) or 'the departed component'}"
        why = None
        if rec is None or rec.get("status") != "run":
            why = f"its decision test {tid} was not run ({(rec or {}).get('reason', 'no harness record')})"
        elif not any(x is False for x in rec.get("perturbation_identity") or []):
            why = f"every perturbation of {tid} is an identity at the calibrated point"
        elif set(rec.get("missing_subtraction") or []) & target:
            why = (f"{tid} skipped targeted packages for want of their subtraction package "
                   f"({sorted(set(rec['missing_subtraction']) & target)})")
        elif not target or max(float((rec.get("benefit_change_by_package") or {}).get(k) or 0.0) for k in target) <= 0:
            why = f"{tid} changed no benefit of {what}"
        out.append({"engine": d.get("engine"), "departure": key, "test": tid, "effective": why is None,
                    "why": why or f"{tid} ran and changed the benefit of {what}"})
    return out


def check_departures(A, recs) -> list[dict]:
    """The same verdicts during the run, with each record's identity flags recomputed at the analysis's calibrated
    point (plan_test with runtime_evidence) and its packages from the analysis."""
    from toolkit.engines import benchmark_coverage as BC
    name = A.eng.describe().name
    ref = f"{type(A.eng).__module__}:{type(A.eng).__name__}"
    tests = {str(t.get("id")): t for t in A.spec["analysis"].get("decision_tests") or []}
    recs2 = {}
    for r in recs:
        tid = str(r.get("test_id"))
        r = dict(r, package_components={k: sorted(v) for k, v in A.pk.items()})
        if r.get("status") == "run" and tid in tests:
            pl = plan_test(A.spec, tests[tid], runtime_evidence(A))
            r["perturbation_identity"] = [bool(x.get("identity")) for x in pl["perturbations"]] \
                if pl["status"] == "runs" else []
        recs2[tid] = r
    deps = [d for d in A.spec.raw.get("engine_departures") or [] if isinstance(d, dict) and d.get("engine") == name]
    return departure_verdicts(deps, BC.departure_targets(A.spec.raw, ref, A.spec.base), recs2)


PRIOR_RANGE_PREFIX = "prior_range_"
FITTED_RANGE_PREFIX = "fitted_range_"
SCENARIO_EXCLUDED_PREFIX = "scenario_excluded_"
ANCHOR_RANGE_PREFIX = "anchor_range_"         # F6 S2-5d review r2: an anchor's external estimate at each interval end


def prior_range_tests(A) -> list[dict]:
    """The automatic prior_range tests: every drawn prior is prior-dominated (the calibration does not condition on
    it), so each gets one (v2d note §3.2)."""
    out = [{"id": f"{PRIOR_RANGE_PREFIX}{k}", "type": "prior_range", "parameter": k, "values": [p.lo, p.hi],
            "automatic": True, "finding": f"decision_test:{PRIOR_RANGE_PREFIX}{k}",
            "text": f"Does the plan change when {k} is at either end of its declared range?",
            "source": p.source} for k, p in A.pr.items()]
    jr = (A.joint or {}).get("ranges") or {}
    for t in out:      # a jointly calibrated parameter: each end of its compatible range, not of its prior
        r = jr.get(t["parameter"])
        if r:
            t.update(values=[float(r[0]), float(r[1])], joint=True,
                     text=f"Does the plan change when {t['parameter']} is at either end of its jointly calibrated "
                          "range?")
    # F6 S1-4: every fitted engine parameter the draws vary that is not a prior gets the same test at each end of its
    # range (of its jointly calibrated range when it has one); an excluded scenario parameter is listed, not run
    have = {t["parameter"] for t in out}
    for k in sorted(A.fr):
        if k in have or k in A.pr:
            continue
        lo, hi = (jr[k] if k in jr else A.fr[k][:2])
        out.append({"id": f"{FITTED_RANGE_PREFIX}{k}", "type": "fitted_range", "parameter": k,
                    "values": [float(lo), float(hi)], "automatic": True, "joint": k in jr,
                    "finding": f"decision_test:{FITTED_RANGE_PREFIX}{k}",
                    "text": f"Does the plan change when the fitted parameter {k} is at either end of its "
                            f"{'jointly calibrated' if k in jr else 'fitted'} range?"})
    from toolkit.spec import priors as PRI
    exc = PRI.excluded_parameters(A.spec.raw["uncertainty"])
    for q_ in A.eng.parameters():
        if q_.kind == "scenario" and q_.name in exc and q_.name not in A.pr:
            out.append({"id": f"{SCENARIO_EXCLUDED_PREFIX}{q_.name}", "type": "scenario_excluded", "parameter": q_.name,
                        "values": [], "automatic": True, "reason": exc[q_.name],
                        "finding": f"decision_test:{SCENARIO_EXCLUDED_PREFIX}{q_.name}",
                        "text": f"Does the plan change with the scenario value {q_.name}?"})
    from toolkit.analysis.burden import anchor_groups
    for g in anchor_groups(getattr(A, "anchor", None)):     # review r3: a group's coupled anchors together
        out.append({"id": f"{ANCHOR_RANGE_PREFIX}{g['name']}", "type": "anchor_range", "anchors": g["rows"],
                    "values": [0.025, 0.975], "ends": g["ends"], "automatic": True,
                    "finding": f"decision_test:{ANCHOR_RANGE_PREFIX}{g['name']}",
                    "text": f"Does the plan change when the external {', '.join(g['outcomes'])} estimates "
                            f"{', '.join(g['rows'])} are together at either end of their published intervals?"})
    if A.method == "posterior":
        # v2d §3.2: a calibration parameter the data do not determine (prior-dominated or partly identified) gets the
        # same automatic test; the calibration is redone with the parameter held at each end of its declared range
        out += [dict(t, calibrated=True) for t in (A.lik or {}).get("prior_range_tests") or []]
    return out



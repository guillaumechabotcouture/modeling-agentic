#!/usr/bin/env python3
"""One generic decision test, `perturb` (W0-B): what the test changes, how, and to what.

    python3 toolkit/spec/perturb.py --self-test

A spec declares

    - id: DTn
      type: perturb
      text: <the question in words, no numbers>
      set:                                   # one or more targets, applied together in every case
        - {target: parameter, name: <engine parameter>, values: [..]}     # the first target is swept
        - {target: parameter, name: <engine parameter>, value: <number>}  # a later one is held (conditional)

Targets and how each is moved (set = values/value, scale, shift, range end):

    parameter           name; values (set; the first target), value (set; held, a later target)
    unit_column         name (a units-table column), units: [ids] | all; one of values | scale | shift | set_from
    cost_item           name (a cost item id); scale (one number). Several cost_item targets form one price case
    calibration_target  units: [ids]; scale
    outcome             component, reference; values (the package's burden over its counterpart's, or "engine")
    burden              references (validation.burden row ids); shares (each in (0, 1])
    interaction         benchmark, components, with_any; values (interaction odds ratios)
    envelope            values (set, USD)
    group_rule          remove: <rule id> | add: {..}
    boundary_engine     (nothing: the boundary check's engine rows replace the emulator's at those units)
    anchor              anchors, ends, values (range end; generated by the harness only)

More than one target is allowed for parameters (the first swept, the others held: a *conditional* test, which
cannot carry a benchmark departure or be the evidence dossier's range test, #294) and for cost items (one price
case). Any other combination is refused, as is an unknown target or an operation a target does not take.

The ten older decision-test types, and the harness's automatic ones, are aliases: `compile(dt)` translates each to a
`perturb` test (lossless: `view(compile(dt)) == dt`, checked below and by the golden records of
toolkit/analysis/dt_golden.py). `view(p)` gives the per-target form each executor branch and reader uses
(toolkit/analysis/decision_tests.py run_one, the design box, the sign-off checks), so a native `perturb` test runs
through the same machinery as its alias. `tests(analysis)` is every declared test in that form. `layer(p, ...)` says
where a test acts: `post_emulator` (re-solved on the point outputs, no model evaluated), `emulator_design` (the
emulator evaluated inside its design box, no engine run) or `engine` (new engine rows, with their count).
Nothing here names a disease.
"""
from __future__ import annotations

import copy
import math
import sys

TYPE = "perturb"
# alias type -> target kind. The automatic types (harness-generated) are aliases too.
ALIASES = {"parameter_value": "parameter", "prior_range": "parameter", "fitted_range": "parameter",
           "scenario_excluded": "parameter", "interaction_rescale": "interaction", "group_rule": "group_rule",
           "envelope": "envelope", "cost_items": "cost_item", "unit_attribute": "unit_column",
           "calibration_target": "calibration_target", "outcome_ratio": "outcome", "burden_scale": "burden",
           "boundary_engine": "boundary_engine", "anchor_range": "anchor"}
# kind -> the alias a native perturb test of that kind executes as
EXEC = {"parameter": "parameter_value", "interaction": "interaction_rescale", "group_rule": "group_rule",
        "envelope": "envelope", "cost_item": "cost_items", "unit_column": "unit_attribute",
        "calibration_target": "calibration_target", "outcome": "outcome_ratio", "burden": "burden_scale",
        "boundary_engine": "boundary_engine", "anchor": "anchor_range"}
# the fields each kind's target takes in a spec (besides `target`)
FIELDS = {"parameter": {"name", "values", "value"}, "interaction": {"benchmark", "components", "with_any", "values"},
          "group_rule": {"remove", "add"}, "envelope": {"values"}, "cost_item": {"name", "scale"},
          "unit_column": {"name", "units", "values", "scale", "shift", "set_from"},
          "calibration_target": {"units", "scale"}, "outcome": {"component", "reference", "values"},
          "burden": {"references", "shares"}, "boundary_engine": set()}
AUTOMATIC = ("anchor",)                       # kinds only the harness generates
UNIT_OPS = ("values", "scale", "shift", "set_from")
NESTED = {"unit_attribute": "unit_attribute", "calibration_target": "calibration_target",
          "outcome_ratio": "outcome_ratio", "burden_scale": "burden_scale"}   # alias -> its block's key
EVALUATED = ("parameter", "unit_column", "cost_item", "calibration_target", "anchor")   # kinds that evaluate the model
META = ("type", "set", "alias", "conditional", "layer")
TOP = ("id", "type", "text", "finding", "set", "conditional")     # a spec's perturb test, at its top level


def _isnum(x) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(float(x))


def compile(dt: dict) -> dict:  # noqa: A001 -- the alias compiler
    """A decision test as a `perturb` test. A native one is returned as a copy; an alias is translated (its type kept
    as `alias`); a field the translation does not take stays at the top level, so nothing is lost. ValueError for a
    type that is neither."""
    if not isinstance(dt, dict):
        raise ValueError(f"a decision test is a mapping, not {type(dt).__name__}")
    t = dt.get("type")
    if t == TYPE:
        return copy.deepcopy(dt)
    if t not in ALIASES:
        raise ValueError(f"decision test {dt.get('id')}: unknown type {t!r}")
    kind, rest = ALIASES[t], {k: v for k, v in dt.items() if k != "type"}
    tgt = {"target": kind}
    targets = [tgt]
    if kind == "parameter":
        for k_from, k_to in (("parameter", "name"), ("values", "values")):
            if k_from in rest:
                tgt[k_to] = rest.pop(k_from)
        if t in ("prior_range", "fitted_range") and "values" in tgt:
            tgt["range_end"] = tgt.pop("values")     # the harness's range-end tests carry their resolved ends
        w = rest.get("with")
        if isinstance(w, dict) and w:
            targets += [{"target": "parameter", "name": k, "value": v} for k, v in rest.pop("with").items()]
    elif kind == "cost_item":
        m, targets = rest.get("multipliers"), []        # a multipliers field it cannot read stays as given
        if isinstance(m, dict) and m:
            targets = [{"target": "cost_item", "name": k, "scale": v} for k, v in rest.pop("multipliers").items()]
    elif kind == "group_rule":
        for k_from, k_to in (("rule", "remove"), ("add", "add")):
            if k_from in rest:
                tgt[k_to] = rest.pop(k_from)
    elif t in NESTED:
        b = rest.get(NESTED[t])
        if isinstance(b, dict) and "target" not in b and "name" not in b:
            rest.pop(NESTED[t])
            tgt.update({("name" if (k == "column" and kind == "unit_column") else k): v for k, v in b.items()})
    else:                                   # interaction, envelope, boundary_engine, anchor: flat fields
        for k in ({"interaction": ("benchmark", "components", "with_any", "values"), "envelope": ("values",),
                   "anchor": ("anchors", "ends", "values")}.get(kind) or ()):
            if k in rest:
                tgt[k] = rest.pop(k)
    return {"type": TYPE, "alias": t, "set": targets, **rest}


def view(p: dict) -> dict:
    """The per-target form a `perturb` test executes as (its alias's fields), for the executor and every reader. A test
    of another type is returned as it is; a `perturb` test whose targets cannot be read is too (validation reports
    it: problems)."""
    if not isinstance(p, dict) or p.get("type") != TYPE:
        return p
    try:
        return _view(p)
    except (TypeError, ValueError, KeyError, AttributeError, IndexError):
        return p


def _view(p: dict) -> dict:
    targets = p["set"]
    kinds = {t["target"] for t in targets}
    alias = p.get("alias")
    kind = ALIASES[alias] if alias else next(iter(kinds))
    if kinds - {kind} or (not targets and kind != "cost_item"):
        raise ValueError("mixed targets")
    out = {k: v for k, v in p.items() if k not in META}
    out["type"] = alias or EXEC[kind]
    first = targets[0] if targets else {}
    if kind == "parameter":
        for k_from, k_to in (("name", "parameter"), ("values", "values"), ("range_end", "values")):
            if k_from in first:
                out[k_to] = first[k_from]
        if len(targets) > 1:
            out["with"] = {t["name"]: t["value"] for t in targets[1:]}
    elif kind == "cost_item":
        if targets:
            out["multipliers"] = {t["name"]: t["scale"] for t in targets}
    elif kind == "group_rule":
        for k_from, k_to in (("remove", "rule"), ("add", "add")):
            if k_from in first:
                out[k_to] = first[k_from]
    elif out["type"] in NESTED and NESTED[out["type"]] not in out:     # a block compile could not read stays as given
        out[NESTED[out["type"]]] = {("column" if (k == "name" and kind == "unit_column") else k): v
                                    for k, v in first.items() if k != "target"}
    else:
        out.update({k: v for k, v in first.items() if k != "target"})
    if len(targets) > 1 and kind not in ("parameter", "cost_item"):
        raise ValueError("several targets")
    return out


def conditional(p: dict) -> bool:
    """A test that holds a second parameter in every case is conditional on it (#294): it carries no benchmark
    departure and is no dossier range test."""
    ts = p.get("set") if isinstance(p, dict) else None
    return isinstance(ts, list) and sum(isinstance(t, dict) and t.get("target") == "parameter" for t in ts) > 1


def problems(p: dict) -> list[str]:
    """Structural problems of a spec-declared `perturb` test (the per-target checks then run on view(p), as for its
    alias): the set, each target's kind, fields and operation, the combinations allowed, `conditional`."""
    i = p.get("id")
    bad = []
    if "alias" in p:
        bad.append(f"decision test {i}: alias is set by the harness when it translates an older type; a spec does not "
                   "declare it")
    top = sorted(set(map(str, p)) - set(TOP))
    if top:
        bad.append(f"decision test {i}: a perturb test takes {', '.join(TOP)} at its top level, not {top} (what it "
                   "moves goes in its targets)")
    ts = p.get("set")
    if not (isinstance(ts, list) and ts and all(isinstance(t, dict) for t in ts)):
        return bad + [f"decision test {i}: set is a non-empty list of targets ({{target: <kind>, ..}})"]
    kinds = [t.get("target") for t in ts]
    for n, t in enumerate(ts):
        k = t.get("target")
        if k in AUTOMATIC:
            bad.append(f"decision test {i}: target {k} is generated by the harness only")
            continue
        if k not in FIELDS:
            bad.append(f"decision test {i}: unknown target {k!r} (known: {', '.join(sorted(FIELDS))})")
            continue
        extra = sorted(set(t) - FIELDS[k] - {"target"})
        if "range_end" in t:
            bad.append(f"decision test {i}: range_end tests are generated by the harness (prior_range_, "
                       "fitted_range_); a spec sets values")
        elif extra:
            bad.append(f"decision test {i}: target {k} does not take {extra} (it takes {sorted(FIELDS[k])})")
        if k == "parameter":
            op = "values" if n == 0 else "value"
            if set(t) & {"values", "value"} != {op}:
                bad.append(f"decision test {i}: the {'first' if n == 0 else 'held'} parameter target sets {op}"
                           + (" (the values swept)" if n == 0 else " (one number, held in every case)"))
            elif n and not _isnum(t["value"]):
                bad.append(f"decision test {i}: held parameter {t.get('name')!r}: value is a finite number")
            if not isinstance(t.get("name"), str) or not t.get("name"):
                bad.append(f"decision test {i}: a parameter target names its engine parameter (name)")
        elif k == "unit_column" and len(set(t) & set(UNIT_OPS)) != 1:
            bad.append(f"decision test {i}: a unit_column target takes exactly one of {', '.join(UNIT_OPS)}")
        elif k == "cost_item" and not (_isnum(t.get("scale")) and t["scale"] > 0):
            bad.append(f"decision test {i}: cost item {t.get('name')!r}: scale is a positive number")
        elif k == "group_rule" and len(set(t) & {"remove", "add"}) != 1:
            bad.append(f"decision test {i}: a group_rule target takes remove or add")
    ks = set(kinds)
    if len(ts) > 1 and not (ks == {"parameter"} or ks == {"cost_item"}):
        bad.append(f"decision test {i}: targets {sorted(map(str, ks))} cannot be applied together (several targets: "
                   "parameters, the first swept and the others held, or cost items, one price case)")
    names = [str(t.get("name")) for t in ts if t.get("target") in ("parameter", "cost_item")]
    if len(set(names)) != len(names):
        bad.append(f"decision test {i}: a target is named twice ({sorted({x for x in names if names.count(x) > 1})})")
    if "conditional" in p and p["conditional"] is not conditional(p):
        bad.append(f"decision test {i}: conditional is {conditional(p)} for this set (true exactly when a second "
                   "parameter is held); it is derived, so leave it out or state it as derived")
    return bad


def tests(analysis) -> list:
    """Every declared decision test of an `analysis` block in its per-target form (view), for the readers."""
    an = analysis if isinstance(analysis, dict) else {}
    return [view(t) for t in an.get("decision_tests") or [] if isinstance(t, dict)]


def cases(p: dict) -> int:
    """How many cases a test evaluates (its first target's sweep)."""
    x = view(p) if p.get("type") == TYPE else p
    t = x.get("type")
    if t in ("cost_items", "calibration_target", "boundary_engine", "group_rule"):
        return 1
    if t == "unit_attribute":
        ua = x.get("unit_attribute") or {}
        return 1 if "set_from" in ua else len(next((ua[k] for k in UNIT_OPS if k in ua), None) or [])
    if t == "outcome_ratio":
        return len((x.get("outcome_ratio") or {}).get("values") or [])
    if t == "burden_scale":
        return len((x.get("burden_scale") or {}).get("shares") or [])
    return len(x.get("values") or [])


def layer(p: dict, evaluation: str, n_units: int, n_packages: int) -> dict:
    """Where a test acts and what it costs: {layer, cases, engine_rows}. post_emulator: re-solved on the point
    outputs; emulator_design: the emulator evaluated inside its design box; engine: each case evaluates every unit and
    package on the engine (direct evaluation)."""
    q = compile(p)
    kind = (q.get("set") or [{}])[0].get("target") if q.get("set") else ALIASES.get(q.get("alias"), "cost_item")
    try:
        n = cases(q)
    except (TypeError, AttributeError, ValueError):      # a malformed test is refused by its own branch, not here
        n = None
    lay = "post_emulator" if kind not in EVALUATED else "emulator_design" if evaluation == "emulator" else "engine"
    rows = 0 if lay != "engine" else None if n is None else int(n) * int(n_units) * int(n_packages)
    return {"layer": lay, "cases": n, "engine_rows": rows}


# ------------------------------------------------------------------ self-test
def _self_test() -> int:
    fails = []

    def ok(cond, msg):
        print(("PASS " if cond else "FAIL ") + msg)
        if not cond:
            fails.append(msg)

    # DT_ALIAS_ROUNDTRIP: every older type (as the self-tests and runs write them) compiles to perturb and back
    shapes = [
        {"id": "DT1", "type": "interaction_rescale", "text": "t", "benchmark": "B1", "components": ["b"],
         "with_any": ["a"], "values": [0.8, 1.2], "finding": "decision_test:DT1"},
        {"id": "DTx", "type": "parameter_value", "parameter": "dw", "values": [0.001], "text": "t"},
        {"id": "DTw", "type": "parameter_value", "parameter": "dw", "values": [0.1, 0.2], "with": {"eff_a": 0.75}},
        {"id": "DTm", "type": "parameter_value", "parameter": "dw", "values": [0.1], "with": "bad"},
        {"id": "prior_range_k", "type": "prior_range", "parameter": "k", "values": [0.1, 0.9], "automatic": True,
         "source": "s", "joint": True},
        {"id": "fitted_range_k", "type": "fitted_range", "parameter": "k", "values": [1, 2], "automatic": True},
        {"id": "scenario_excluded_s", "type": "scenario_excluded", "parameter": "s", "values": [], "reason": "r"},
        {"id": "DTg", "type": "group_rule", "rule": "zone_a", "text": "t"},
        {"id": "DTa", "type": "group_rule", "add": {"id": "x", "by": "zone", "components": ["a"]}},
        {"id": "env", "type": "envelope", "values": [9000, 12000]},
        {"id": "DTc", "type": "cost_items", "multipliers": {"ka": 1e9, 7: 0.5}},
        {"id": "DTc0", "type": "cost_items", "multipliers": {}},
        {"id": "DTc9", "type": "cost_items"},
        {"id": "DTu", "type": "unit_attribute", "text": "t", "unit_attribute": {"column": "inc", "units": "all",
                                                                                 "scale": [0.5, 2]}},
        {"id": "DTu2", "type": "unit_attribute", "unit_attribute": "not a mapping"},
        {"id": "DTt", "type": "calibration_target", "calibration_target": {"units": ["1"], "scale": 0.8},
         "conflict": True},
        {"id": "DTo", "type": "outcome_ratio", "outcome_ratio": {"component": "a", "reference": "b",
                                                                 "values": [0.5, "engine"]}},
        {"id": "DTb", "type": "burden_scale", "burden_scale": {"references": ["r1"], "shares": [0.5, 1.0]}},
        {"id": "DTbe", "type": "boundary_engine", "text": "t"},
        {"id": "anchor_range_N", "type": "anchor_range", "anchors": ["N0"], "values": [0.025, 0.975],
         "ends": {0.025: {"anchor:N0": 1.0}, 0.975: {"anchor:N0": 2.0}}, "automatic": True},
    ]
    seen, by_id = set(), {dt["id"]: dt for dt in shapes}
    for dt in shapes:
        p = compile(dt)
        seen.add(dt["type"])
        ok(p["type"] == TYPE and p["alias"] == dt["type"] and view(p) == dt,
           f"PT1 {dt['type']} ({dt['id']}) compiles to perturb and back unchanged: {p} -> {view(p)}")
    ok(seen == set(ALIASES), f"PT1b every alias is covered ({sorted(set(ALIASES) - seen)} missing)")
    ok(compile({"id": "x", "type": "cost_items", "multipliers": {"k1": 2.0, "k2": 0.5}})["set"]
       == [{"target": "cost_item", "name": "k1", "scale": 2.0}, {"target": "cost_item", "name": "k2", "scale": 0.5}],
       "PT2 a cost_items test is one cost_item target per item, applied together")
    ok(compile(shapes[2])["set"][1:] == [{"target": "parameter", "name": "eff_a", "value": 0.75}]
       and conditional(compile(shapes[2])) and not conditional(compile(shapes[1])),
       "PT3 a parameter_value test's companions are held parameter targets, which make it conditional")
    ok(compile(shapes[4])["set"][0].get("range_end") == [0.1, 0.9], "PT4 a prior_range test is a range end")
    try:
        compile({"id": "x", "type": "magic"})
        ok(False, "PT5 an unknown type is refused")
    except ValueError as e:
        ok("unknown type" in str(e), f"PT5 an unknown type is refused: {e}")

    # a native perturb test executes as its alias (the same machinery), with the same fields
    nat = {"id": "DTp", "type": "perturb", "text": "t", "set": [
        {"target": "parameter", "name": "dw", "values": [0.1, 0.2]},
        {"target": "parameter", "name": "eff_a", "value": 0.75}]}
    v = view(nat)
    ok(v == {"id": "DTp", "text": "t", "type": "parameter_value", "parameter": "dw", "values": [0.1, 0.2],
             "with": {"eff_a": 0.75}} and not problems(nat),
       f"PT6 DT_PERTURB_JOINT: two parameter targets run as a test with a companion held in every case: {v}")
    nu = {"id": "DTq", "type": "perturb", "text": "t",
          "set": [{"target": "unit_column", "name": "inc", "units": ["1", "2"], "shift": [0.1]}]}
    ok(view(nu)["unit_attribute"] == {"column": "inc", "units": ["1", "2"], "shift": [0.1]} and not problems(nu),
       f"PT7 a unit_column target with shift runs as a unit_attribute test: {view(nu)}")
    nc = {"id": "DTk", "type": "perturb", "text": "t", "set": [{"target": "cost_item", "name": "k1", "scale": 2.0},
                                                                {"target": "cost_item", "name": "k2", "scale": 0.5}]}
    ok(view(nc) == {"id": "DTk", "text": "t", "type": "cost_items", "multipliers": {"k1": 2.0, "k2": 0.5}}
       and not problems(nc), f"PT8 two cost_item targets are one price case: {view(nc)}")
    ok(tests({"decision_tests": [nat, shapes[7], "junk"]}) == [v, shapes[7]],
       "PT9 tests() gives every declared test in its per-target form (an older type unchanged)")

    # DT_PERTURB_UNKNOWN_TARGET_REFUSED and the other refusals
    def refused(p, frag, label):
        e = problems(p)
        ok(any(frag in x for x in e), f"{label}: {e}")
    refused({"id": "a", "type": "perturb", "set": [{"target": "magic", "name": "x"}]}, "unknown target",
            "PT10 DT_PERTURB_UNKNOWN_TARGET_REFUSED")
    refused({"id": "a", "type": "perturb", "set": []}, "non-empty list", "PT11 an empty set is refused")
    refused({"id": "a", "type": "perturb", "set": [{"target": "parameter", "name": "p", "values": [1]},
                                                   {"target": "envelope", "values": [1]}]},
            "cannot be applied together", "PT12 targets of different kinds together are refused")
    refused({"id": "a", "type": "perturb", "set": [{"target": "parameter", "name": "p", "values": [1],
                                                    "scale": 2}]}, "does not take", "PT13 a field a target does "
            "not take is refused")
    refused({"id": "a", "type": "perturb", "set": [{"target": "parameter", "name": "p", "range_end": [1, 2]}]},
            "generated by the harness", "PT14 a range end is the harness's")
    refused({"id": "a", "type": "perturb", "set": [{"target": "anchor", "anchors": ["N"]}]},
            "generated by the harness only", "PT15 an anchor target is the harness's")
    refused(dict(nat, alias="prior_range"), "alias is set by the harness", "PT16 a spec cannot declare an alias")
    refused(dict(nat, **{"with": {"k": 1.0}}), "at its top level", "PT16b an older type's field at the top level is "
            "refused (what a test moves is in its targets)")
    refused({"id": "a", "type": "perturb", "set": [{"target": "unit_column", "name": "c", "scale": [2],
                                                    "shift": [1]}]}, "exactly one of", "PT17 one unit operation")
    refused({"id": "a", "type": "perturb", "set": [{"target": "parameter", "name": "p", "values": [1]},
                                                   {"target": "parameter", "name": "p", "value": 2}]},
            "named twice", "PT18 a parameter named twice is refused")
    # DT_CONDITIONAL_NO_DEPARTURE (declaration side): a joint test is conditional and cannot say otherwise
    refused(dict(nat, conditional=False), "conditional is True", "PT19 a joint test cannot declare conditional: false")
    ok(not problems(dict(nat, conditional=True)), "PT19b conditional: true on a joint test is accepted")
    bad_view = {"id": "a", "type": "perturb", "set": "junk"}
    ok(view(bad_view) is bad_view, "PT20 an unreadable perturb test is left to validation (view returns it)")

    # DT_PERTURB_LAYER_COST: the layer each test acts on and its engine rows
    ok(layer(nat, "emulator", 10, 4) == {"layer": "emulator_design", "cases": 2, "engine_rows": 0}
       and layer(nat, "direct", 10, 4) == {"layer": "engine", "cases": 2, "engine_rows": 80}
       and layer(by_id["env"], "direct", 10, 4)["layer"] == "post_emulator"
       and layer(by_id["DTo"], "emulator", 10, 4) == {"layer": "post_emulator", "cases": 2, "engine_rows": 0}
       and layer(nu, "direct", 5, 3)["engine_rows"] == 15 and layer(nc, "direct", 5, 3)["engine_rows"] == 15,
       "PT21 DT_PERTURB_LAYER_COST: post_emulator, emulator_design or engine, with the engine row count")

    if fails:
        print(f"FAILED: {len(fails)} case(s)")
        return 1
    print("OK: all self-test cases passed.")
    return 0


if __name__ == "__main__":
    if sys.argv[1:2] == ["--self-test"]:
        sys.exit(_self_test())
    print(__doc__)

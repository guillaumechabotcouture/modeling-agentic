#!/usr/bin/env python3
"""A22 (Phase 49 γ): the harness writes the declared limits into the executive summary.

    python3 scripts/declared_limits.py <run_dir>          # the gate's findings
    python3 scripts/declared_limits.py <run_dir> --block  # print the block render_claims inserts
    python3 scripts/declared_limits.py --self-test

E7 attempt 8 ended DECLARE_SCOPE with its main weaknesses declared (allocation
unstable out of sample, SD-007; the trial interaction between nets and spraying
not reproduced while recommending no spraying, SD-002; weakly identified
transmission parameters, SD-008). The writer copied the declarations into
§Limitations, and the executive summary named none of them.

Structural fix (owner rule: structural checks over parsing prose). The writer
does not type these facts. It puts one placeholder, `[DECLARED_LIMITS]`, in the
executive summary, and `scripts/render_claims.py` replaces it with a block
generated here from `scope_declaration.yaml` (the validator's own loader) and
each declaration's decision test (Phase 49 α, `scripts/declaration_tests.py`):
the declaration id, its claim text, and its measured effect on the
recommendation, i.e. whether the decision changes and the recommendation with
and without, or "untested", "exempt: <reason>", or "invalid test (<error>)". A
malformed test is shown as invalid here and reported by α's check, not
suppressed.

The gate check is positional, on the writer's draft (report.unrendered.md, else
manuscript.md) with HTML comments and fenced code removed:
  - the token appears exactly once;
  - it comes before the first body section (a heading that starts with a
    number, or is Introduction / Background / Methods);
  - report.md contains the block as it renders now (so a declaration added or
    changed after rendering is caught).
Required only when scope_declaration.yaml declares something. Otherwise HIGH
`declared_limits_not_rendered` (stage WRITE): an accept blocker that stays
declarable, so ACCEPT is impossible while it is open and a run that ends with
it is DECLARE_SCOPE, not RUN_FAILED. The harness's presentation fix pass
(Phase 49 δ) hands it to the writer.
"""
from __future__ import annotations

import os
import re
import sys
from typing import Optional

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from lib.siblings import load_private  # noqa: E402

TOKEN = "[DECLARED_LIMITS]"
KIND = "declared_limits_not_rendered"
BEGIN = "<!-- declared-limits: generated by the harness from scope_declaration.yaml -->"
END = "<!-- /declared-limits -->"
_COMMENT_RE = re.compile(r"<!--.*?-->", re.S)
_FENCE_RE = re.compile(r"^[ \t]*(```|~~~).*?^[ \t]*\1[^\n]*$", re.S | re.M)
_BODY_HEADING_RE = re.compile(r"^#{1,6}[ \t]+(?:\d|introduction\b|background\b|methods?\b)", re.I | re.M)


def _validator():
    return load_private("validate_critique_yaml", "_ma_declared_limits_")


def _tests():
    try:
        return load_private("declaration_tests", "_ma_declared_limits_")
    except (FileNotFoundError, ImportError, AttributeError):
        return None


def declarations(run_dir: str) -> list[dict]:
    """Declaration entries with a justification (the validator's normalizer)."""
    v = _validator()
    return [e for e in v._load_scope_declarations(run_dir)[1]
            if isinstance(e, dict) and v._entry_has_justification(e)]


def _one_line(x, limit: int = 600) -> str:
    s = " ".join(str(x or "").split())
    return s if len(s) <= limit else s[:limit - 1].rstrip() + "…"


def effect(run_dir: str, entry: dict, mod=None) -> str:
    """The declaration's measured effect on the recommendation, as rendered."""
    if mod is None:
        mod = _tests()
    if entry.get("decision_test") is not None:
        if mod is None or not hasattr(mod, "declaration_test"):
            return "decision test not read (scripts/declaration_tests.py unavailable)"
        res, err = mod.declaration_test(run_dir, entry)
        if err or not isinstance(res, dict):
            return f"invalid test ({_one_line(err or 'no result', 200)})"
        rec = res.get("recommendation") if isinstance(res.get("recommendation"), dict) else {}
        verdict = "changes the recommendation" if res.get("decision_changes") else \
            "does not change the recommendation"
        return (f"tested ({_one_line(entry.get('decision_test'), 120)}): {verdict}; "
                f"with: {_one_line(rec.get('with'), 200)}; without: {_one_line(rec.get('without'), 200)}")
    if mod is not None and hasattr(mod, "exemption"):
        reason = mod.exemption(run_dir, entry)
        if reason:
            return f"exempt: {_one_line(reason, 300)}"
    elif any(k in entry for k in ("specified_by", "owner_amendment")):
        return "exempt: unverified"
    return "untested"


def render_block(run_dir: str) -> str:
    """The block that replaces the token. Deterministic for a given run state."""
    ents = declarations(run_dir)
    mod = _tests()
    lines = [BEGIN, "**What this does not establish.** The run declared these limits "
                    "(scope_declaration.yaml; full text in Limitations):", ""]
    if not ents:
        lines.append("- No limitation was declared.")
    for e in ents:
        did = _one_line(e.get("id") or "(no id)", 40)
        claim = _one_line(e.get("claim") or e.get("description") or e.get("why_unresolved"))
        lines.append(f"- **{did}**: {claim} Effect on the recommendation: {effect(run_dir, e, mod)}.")
    lines.append(END)
    return "\n".join(lines)


def _visible(text: str) -> str:
    """The draft with HTML comments and fenced code blanked (offsets kept)."""
    blank = lambda m: re.sub(r"[^\n]", " ", m.group(0))  # noqa: E731
    return _FENCE_RE.sub(blank, _COMMENT_RE.sub(blank, text))


def expand(run_dir: str, text: str) -> str:
    """render_claims: replace each visible token with the generated block."""
    vis = _visible(text)
    spots = [m.start() for m in re.finditer(re.escape(TOKEN), vis)]
    if not spots:
        return text
    block = render_block(run_dir)
    for pos in reversed(spots):
        text = text[:pos] + block + text[pos + len(TOKEN):]
    return text


def _read(path: str) -> Optional[str]:
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            return f.read()
    except OSError:
        return None


def problems(run_dir: str) -> list[str]:
    draft = _read(os.path.join(run_dir, "report.unrendered.md"))
    if draft is None:
        draft = _read(os.path.join(run_dir, "manuscript.md"))
    report = _read(os.path.join(run_dir, "report.md"))
    if draft is None and report is None:
        return []                     # no draft yet
    if not declarations(run_dir):
        return []
    out = []
    if draft is None:
        out.append("there is no writer's draft (manuscript.md) to place the token in")
    else:
        vis = _visible(draft)
        spots = [m.start() for m in re.finditer(re.escape(TOKEN), vis)]
        body = _BODY_HEADING_RE.search(vis)
        if len(spots) != 1:
            out.append(f"the draft has the token {TOKEN} {len(spots)} times outside comments and code "
                       "(it must appear exactly once)")
        elif body is not None and spots[0] > body.start():
            out.append(f"the token {TOKEN} comes after the first body section "
                       f"(`{vis[body.start():vis.find(chr(10), body.start())].strip()[:60]}`); "
                       "put it in the executive summary")
    if report is not None and render_block(run_dir) not in report:
        out.append("report.md does not contain the declared-limits block as it renders now "
                   "(re-run scripts/render_claims.py after the last change to the draft or the declarations)")
    return out


def gate_findings(run_dir: str) -> list[dict]:
    p = problems(run_dir)
    if not p:
        return []
    return [{"kind": KIND, "severity": "HIGH", "stage": "WRITE", "target_stage": "WRITE",
             "accept_blocker": True, "scope_declarable": True, "key": "declared_limits",
             "claim": ("The declared limits are not in the executive summary as the harness renders them: "
                       + "; ".join(p) + f". Put {TOKEN} once in the executive summary of manuscript.md and "
                       "re-render; do not type the declarations there. ACCEPT is impossible until then.")}]



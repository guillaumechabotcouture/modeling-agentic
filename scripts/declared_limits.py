def _self_test() -> int:
    import shutil
    import tempfile

    import yaml

    fails: list[str] = []

    def ok(c, m):
        if not c:
            fails.append(m)

    def w(d, rel, obj):
        p = os.path.join(d, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w") as f:
            f.write(obj) if isinstance(obj, str) else yaml.safe_dump(obj, f)

    def draft(d, text):
        w(d, "manuscript.md", text)
        rp = os.path.join(d, "report.unrendered.md")
        if os.path.exists(rp):
            os.remove(rp)
        w(d, "report.md", expand(d, text))

    decl = {"declarations": [
        {"id": "SD-007", "blocker_id": "allocation_unstable",
         "claim": "Leave-one-out allocation is UNSTABLE.", "why_unresolved": "w"},
        {"id": "SD-002", "blocker_id": "benchmark_drift", "claim": "B15 interaction not reproduced.",
         "why_unresolved": "w", "decision_test": "models/sufficiency/sd002.yaml"}]}
    head = "# Title\n\n## Executive summary\n\nFund nets.\n\n"
    body = "\n\n## 1. Introduction\n\nText.\n\n## 8. Limitations\n\nSD-007 SD-002 verbatim.\n"
    d = tempfile.mkdtemp(prefix="dl_")
    try:
        ok(gate_findings(d) == [], "DL1 no draft: nothing")
        w(d, "manuscript.md", head + body)
        ok(gate_findings(d) == [], "DL2 a draft and no declarations: the token is not required")
        w(d, "scope_declaration.yaml", decl)
        f = gate_findings(d)
        ok(len(f) == 1 and f[0]["kind"] == KIND and f[0]["accept_blocker"] and f[0]["scope_declarable"]
           and "0 times" in f[0]["claim"], f"DL3 declarations and no token: HIGH accept blocker: {f}")
        draft(d, head + TOKEN + body)
        rep = open(os.path.join(d, "report.md")).read()
        ok(gate_findings(d) == [] and "**SD-007**: Leave-one-out allocation is UNSTABLE." in rep
           and "**SD-002**" in rep and TOKEN not in rep, f"DL4 token once in the summary, rendered: {gate_findings(d)}")
        ok("Effect on the recommendation: untested" in rep, "DL5 a declaration without a test renders 'untested'")
        ok(("invalid test" in rep or "not read" in rep) and "SD-002" in rep,
           "DL6 a declaration whose test file is missing renders an invalid (or unread) test, not nothing")
        w(d, "models/sufficiency/sd002.yaml", {"finding": "benchmark_drift", "varied": "interaction OR",
                                               "criterion": "package changes in >10% of units",
                                               "decision_changes": False,
                                               "recommendation": {"with": "no IRS", "without": "no IRS"}})
        ok(KIND in [x["kind"] for x in gate_findings(d)] or _tests() is None,
           "DL7 the test result changed after rendering: the rendered block is stale")
        draft(d, head + TOKEN + body)
        rep = open(os.path.join(d, "report.md")).read()
        ok(gate_findings(d) == [] and ("does not change the recommendation; with: no IRS; without: no IRS" in rep
                                       or _tests() is None),
           f"DL8 a valid test renders its verdict and the with/without recommendation: {gate_findings(d)}")
        # --- Codex round 1 on the summary parser: each scenario, under the new design ---
        draft(d, "# Title\n\n## Key messages\n\n" + TOKEN + body)
        ok(gate_findings(d) == [], "DL9 (Codex: headings) any summary heading works; no heading list")
        draft(d, "# A summary of the allocation\n\n" + TOKEN + "\n\n## 1. Introduction\n\nx\n")
        ok(gate_findings(d) == [], "DL10 (Codex: title hijack) a title with 'summary' in it changes nothing")
        draft(d, head + "Allocation is unstable (SD-7); see SD - 002.\n" + body)
        ok(KIND in [x["kind"] for x in gate_findings(d)],
           "DL11 (Codex: aliases, paraphrase, whitespace) typed or paraphrased ids do not count; only the token")
        draft(d, head + "<!-- " + TOKEN + " -->\n" + body)
        ok("0 times" in (gate_findings(d) or [{}])[0].get("claim", ""),
           "DL12 (Codex: HTML comments) a token inside a comment is not a token")
        draft(d, head + "```\n" + TOKEN + "\n```\n" + body)
        ok("0 times" in (gate_findings(d) or [{}])[0].get("claim", ""), "DL13 a token in a code fence is not a token")
        w(d, "models/claims_spec.yaml", {"claims": [{"id": "sd002_crit", "source_artifact":
                                                     "models/sufficiency/sd002.yaml", "source_field": "criterion"}]})
        draft(d, head + "[CLAIM:sd002_crit] (SD-002, SD-007)\n" + body)
        ok(KIND in [x["kind"] for x in gate_findings(d)],
           "DL14 (Codex: metadata claims) a claim read from the test file does not stand in for the block")
        draft(d, head + TOKEN + "\n\n" + TOKEN + body)
        ok("2 times" in (gate_findings(d) or [{}])[0].get("claim", ""), "DL15 two tokens: flagged")
        draft(d, head + body + "\n" + TOKEN + "\n")
        ok("after the first body section" in (gate_findings(d) or [{}])[0].get("claim", ""),
           "DL16 the token after §1: flagged")
        w(d, "manuscript.md", head + TOKEN + body)
        w(d, "report.md", head + "Hand-typed: SD-007 and SD-002." + body)
        ok("does not contain the declared-limits block" in (gate_findings(d) or [{}])[0].get("claim", ""),
           "DL17 a report with the token but without the rendered block (not re-rendered, or hand-edited): flagged")
        w(d, "report.unrendered.md", head + TOKEN + body)
        w(d, "manuscript.md", head + "no token here" + body)
        w(d, "report.md", expand(d, head + TOKEN + body))
        ok(gate_findings(d) == [], "DL18 the unrendered snapshot is the draft the report was rendered from")
    finally:
        shutil.rmtree(d, ignore_errors=True)
    if fails:
        for m in fails:
            print("FAIL:", m)
        return 1
    print("OK: all self-test cases passed.")
    return 0


def main(argv=None) -> int:
    import argparse
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("run_dir", nargs="?")
    ap.add_argument("--block", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args(argv)
    if a.self_test:
        return _self_test()
    if not a.run_dir:
        ap.error("run_dir required")
    if a.block:
        print(render_block(a.run_dir))
        return 0
    fs = gate_findings(a.run_dir)
    for x in fs:
        print(f"[{x['severity']}] {x['kind']}: {x['claim'][:400]}")
    return 1 if fs else 0


if __name__ == "__main__":
    sys.exit(main())
